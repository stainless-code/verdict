import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const docsRoot = fileURLToPath(new URL("..", import.meta.url));
const repoRoot = fileURLToPath(new URL("../../..", import.meta.url));
const siteIndex = join(
  docsRoot,
  "dist",
  ".well-known",
  "agent-skills",
  "index.json",
);

interface PublishedSkill {
  name: string;
  where: string;
}

const fail = (lines: readonly string[]): never => {
  console.error(lines.join("\n"));
  process.exit(1);
};

const declaredName = (file: string): string => {
  const markdown = readFileSync(file, "utf8");
  const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---/u.exec(markdown)?.[1];
  const raw =
    frontmatter === undefined
      ? undefined
      : /^name:[ \t]*(.*)$/mu.exec(frontmatter)?.[1];
  const name = raw?.trim().replace(/^["']|["']$/gu, "");
  if (name === undefined || name === "") {
    return fail([
      `skill names: ${relative(repoRoot, file)} declares no \`name:\`.`,
      "Agent indexes key skills by that field.",
    ]);
  }
  return name;
};

const skillsInDirectory = (dir: string): PublishedSkill[] =>
  readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((a, b) => (a < b ? -1 : 1))
    .flatMap((entry) => {
      const file = join(dir, entry, "SKILL.md");
      return existsSync(file)
        ? [{ name: declaredName(file), where: relative(repoRoot, file) }]
        : [];
    });

const skillsInIndex = (file: string): PublishedSkill[] => {
  const index = JSON.parse(readFileSync(file, "utf8")) as {
    skills?: { name?: unknown }[];
  };
  const where = `${relative(repoRoot, file)} (index entry)`;
  return (index.skills ?? []).flatMap((skill) =>
    typeof skill.name === "string" && skill.name !== ""
      ? [{ name: skill.name, where }]
      : [fail([`skill names: an entry in ${where} has no name.`])],
  );
};

const collisions = (skills: readonly PublishedSkill[]): string[] => {
  const byName = new Map<string, string[]>();
  for (const skill of skills) {
    byName.set(skill.name, [...(byName.get(skill.name) ?? []), skill.where]);
  }
  return [...byName]
    .filter(([, where]) => where.length > 1)
    .map(([name, where]) => `  "${name}": ${where.join(" and ")}`);
};

const main = (): void => {
  if (!existsSync(siteIndex)) {
    fail([
      `skill names: no built agent-skills index at ${relative(repoRoot, siteIndex)}.`,
      "Run this after `blume build`; the docs `build` script does.",
    ]);
  }

  const site = skillsInIndex(siteIndex);
  const published = [...skillsInDirectory(join(repoRoot, "skills")), ...site];

  const found = collisions(published);
  if (found.length > 0) {
    fail([
      "skill names: two published skills share a name.",
      ...found,
      "",
      "An agent index keys skills by `name:`, so a harness that sees both loads",
      "whichever wins and follows instructions written for the other job. Rename",
      "the docs-side skill — its directory under `apps/docs/skills/` and the",
      "`name:` in its SKILL.md.",
      "",
      "A site skill generated by Blume is named after the site title, so it takes",
      "the name of the payload in `skills/`; keep `agents.skillMd: false` in",
      "`apps/docs/blume.config.ts` and ship the docs guide as its own skill.",
    ]);
  }

  console.log(
    `skill names distinct: ${published
      .map((skill) => skill.name)
      .sort()
      .join(", ")}`,
  );
};

main();
