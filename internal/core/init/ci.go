package initcore

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/stainless-code/verdict/internal/agentcatalog"
	"github.com/stainless-code/verdict/internal/core"
)

const (
	// workflowBase is the committed workflow's file name inside a provider's
	// workflow directory.
	workflowBase = "verdict-review.yml"
	// workflowMode is the committed workflow's mode: nothing executes the file.
	workflowMode = 0o644
	// defaultModelFlag is the argument an agent takes a model name on when its
	// catalog row names none.
	defaultModelFlag = "--model"
	// defaultAgent is the agent a --ci run wires when --agent names none.
	defaultAgent = "claude"
	// sharedSkillAgent is the skills directory every agent without one of its
	// own installs into: `verdict skill install --agent agents` is the only
	// name the installer accepts for those rows.
	sharedSkillAgent = "agents"
)

// keySecretName is the shape of one repository secret name. The name reaches a
// YAML env entry and a shell assignment, so anything looser is injection.
var keySecretName = regexp.MustCompile(`^[A-Z_][A-Z0-9_]*$`)

// ciProvider is one CI provider `--ci` can write for: the workflow it lands,
// the directory components init pins and creates (parent first), the header
// naming the command, and the vocabulary its steps interpolate. Adding a
// provider is one table row.
type ciProvider struct { //nolint:govet // the registry's field order documents the design; alignment is irrelevant
	name string
	dirs []string
	base string
	vars *ciVars
}

// ciVars is one provider's vocabulary, rendered from literals in one place.
// Every fragment is pre-indented and newline-terminated so the template can
// drop it at a line start.
type ciVars struct {
	repository     string // the ${{ … }} expression naming the repository
	pr             string // the ${{ … }} expression naming the pull request
	forkGuard      string // the job-level if: value
	permissions    string // the top-level permissions block; "" where absent
	jobPermissions string // the job-level permissions block; "" where absent
	install        string // the whole "Install verdict" step
	hostEnv        string // env lines every host-calling step carries
	agentClear     string // env lines the agent step zeroes
	fetchFlag      string // "" | " --provider forgejo"
	readyStep      string // the readiness step; "" where the host cannot run it
}

// Name is the --ci value, also the envelope's data.ci. It is exported for the
// static archtest, which grades every provider the registry declares.
func (p ciProvider) Name() string { return p.name }

// path is the committed workflow a provider writes, relative to the repository
// root.
func (p ciProvider) path() string {
	return p.dirs[len(p.dirs)-1] + "/" + p.base
}

// header names the generator and its review obligation, and never the build's
// version, so the bytes are identical across builds.
func (p ciProvider) header() string {
	return "# Generated by `verdict init --ci " + p.name + "`. Review before committing.\n" +
		"#\n" +
		"# Commit this file: every pull request then runs verdict on your runner with\n" +
		"# your agent and your own model key. Regenerate after upgrading verdict.\n"
}

// Providers returns every provider `--ci` accepts, in declaration order.
func Providers() []ciProvider {
	return []ciProvider{githubProvider(), forgejoProvider()}
}

// LookupCI resolves one --ci value, reporting whether the provider exists.
func LookupCI(name string) (ciProvider, bool) {
	for _, ci := range Providers() {
		if ci.name == name {
			return ci, true
		}
	}
	return ciProvider{}, false
}

// CIValues is the enum every --ci hint and usage error prints.
func CIValues() string {
	names := make([]string, 0, len(Providers()))
	for _, ci := range Providers() {
		names = append(names, ci.name)
	}
	return strings.Join(names, "|")
}

// githubProvider is the GitHub Actions target: the shipped every-PR workflow,
// byte-identical to the one STA-465 established.
func githubProvider() ciProvider {
	vars := &ciVars{
		repository:     "${{ github.repository }}",
		pr:             "${{ github.event.pull_request.number }}",
		forkGuard:      "github.event.pull_request.head.repo.full_name == github.repository",
		permissions:    "permissions:\n  contents: read\n\n",
		jobPermissions: "    permissions:\n      contents: read\n      pull-requests: write\n",
		install: "      - name: Install verdict\n" +
			"        uses: stainless-code/verdict/setup-verdict@" + SetupVerdictPin +
			" # " + SetupVerdictVersion + "\n" +
			"        with:\n" +
			"          version: ${{ vars.VERDICT_VERSION }}\n",
		hostEnv:    "          GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}\n",
		agentClear: "          GH_TOKEN: \"\"\n          GITHUB_TOKEN: \"\"\n",
	}
	vars.readyStep = readinessStep(vars)
	return ciProvider{
		name: "github",
		dirs: []string{".github", ".github/workflows"},
		base: workflowBase,
		vars: vars,
	}
}

// forgejoProvider is the Forgejo Actions target: the same pipeline, wired to
// verdict's native Forgejo provider.
func forgejoProvider() ciProvider {
	return ciProvider{
		name: "forgejo",
		dirs: []string{".forgejo", ".forgejo/workflows"},
		base: workflowBase,
		vars: &ciVars{
			repository: "${{ github.repository }}",
			pr:         "${{ github.event.pull_request.number }}",
			forkGuard:  "github.event.pull_request.head.repo.full_name == github.repository",
			// Forgejo has no granular permission model, so both blocks would be
			// inert YAML.
			permissions:    "",
			jobPermissions: "",
			// A short-form action reference resolves through DEFAULT_ACTIONS_URL,
			// which does not mirror this repository. The URL form is explicit.
			install: "      - name: Install verdict\n" +
				"        uses: https://github.com/stainless-code/verdict/setup-verdict@" +
				SetupVerdictPin + " # " + SetupVerdictVersion + "\n" +
				"        with:\n" +
				"          version: ${{ vars.VERDICT_VERSION }}\n",
			hostEnv: "          FORGEJO_HOST: ${{ github.server_url }}\n" +
				"          FORGEJO_TOKEN: ${{ github.token }}\n",
			// Forgejo injects FORGEJO_TOKEN and GITHUB_TOKEN into every step.
			agentClear: "          GH_TOKEN: \"\"\n" +
				"          GITHUB_TOKEN: \"\"\n" +
				"          FORGEJO_TOKEN: \"\"\n",
			fetchFlag: " --provider forgejo",
			// ready --check refuses provider-unimplemented on a Forgejo bundle,
			// so the step would fail every pull request. The gate still blocks.
			readyStep: "",
		},
	}
}

// readinessStep renders the spend-saving pre-check for a provider that can run
// it, reusing the provider's own host env.
func readinessStep(vars *ciVars) string {
	return newlineStr + "      - name: Readiness pre-check (saves agent spend)" + newlineStr +
		"        env:" + newlineStr +
		"          VERDICT_REPOSITORY: " + vars.repository + newlineStr +
		"          VERDICT_PR: " + vars.pr + newlineStr +
		vars.hostEnv +
		"        shell: bash" + newlineStr +
		"        run: |" + newlineStr +
		"          verdict ready \"$VERDICT_REPOSITORY\" \"$VERDICT_PR\" --check" + newlineStr
}

// renderOptions is the generated pipeline's per-agent half. keyEnv and
// keySecret are two names: the agent reads the first, the repository stores the
// key under the second. So `--key-secret REVIEW_KEY` on `claude` renders
// `ANTHROPIC_API_KEY: ${{ secrets.REVIEW_KEY }}`, never a `REVIEW_KEY:`
// variable claude does not read.
type renderOptions struct {
	agent      string
	skillAgent string
	keyEnv     string
	keySecret  string
	modelFlag  string
	permission string
	install    string
}

// workflowFor renders the workflow for the requested agent, or returns nil
// when the invocation is not a --ci run.
func (st *state) workflowFor() ([]byte, *core.RefusalError) {
	if st.req.CI == "" {
		return nil, nil
	}
	return RenderWorkflow(st.ci.name, st.req.Agent, st.req.KeySecret)
}

// RenderWorkflow renders one provider's every-PR workflow for one shipped
// agent name, taking the key secret from the catalog row unless keySecret names
// one. It is the byte contract the init tests and internal/archtest grade. An
// unknown provider refuses naming the accepted values: the CLI rejects it as a
// usage error first, so this is the service-level defense.
func RenderWorkflow(ci, agent, keySecret string) ([]byte, *core.RefusalError) {
	provider, ok := LookupCI(ci)
	if !ok {
		return nil, &core.RefusalError{
			Code:    codeBadSettings,
			Message: fmt.Sprintf("unknown --ci '%s' (want %s)", ci, CIValues()),
		}
	}
	opts, ref := wiredOptions(agent, keySecret)
	if ref != nil {
		return nil, ref
	}
	return renderWorkflow(provider, &opts), nil
}

// wiredOptions resolves one agent name and secret name into render inputs. The
// secret defaults to the catalog row's documented key variable; a row that
// documents none needs an explicit --key-secret.
func wiredOptions(agent, keySecret string) (renderOptions, *core.RefusalError) {
	if keySecret != "" && !keySecretName.MatchString(keySecret) {
		return renderOptions{}, &core.RefusalError{
			Code: codeBadSettings,
			Message: fmt.Sprintf("invalid --key-secret '%s' "+
				"(want an env name like ANTHROPIC_API_KEY)", keySecret),
		}
	}
	row, ok := agentcatalog.Lookup(agent)
	if !ok || row.Launch == nil {
		return renderOptions{}, &core.RefusalError{
			Code:    codeUnknownAgent,
			Message: fmt.Sprintf("unknown agent '%s' (known: %s)", agent, launchNames()),
		}
	}
	secret := firstNonEmpty(keySecret, row.Launch.KeyEnv)
	if secret == "" {
		return renderOptions{}, &core.RefusalError{
			Code: codeBadSettings,
			Message: fmt.Sprintf("agent '%s' has no documented key variable; "+
				"pass --key-secret <NAME> naming the repository secret that holds its key", agent),
		}
	}
	return renderOptions{
		agent:      agent,
		skillAgent: skillAgent(row),
		keyEnv:     firstNonEmpty(row.Launch.KeyEnv, secret),
		keySecret:  secret,
		modelFlag:  firstNonEmpty(row.Launch.ModelFlag, defaultModelFlag),
		permission: row.Launch.PermissionHint,
		install:    row.Launch.Install,
	}, nil
}

// skillAgent is the name `verdict skill install` takes for this row: the agent
// itself when its catalog row declares a skills directory, else the shared
// agents directory. Most launchable rows declare none, and the installer
// refuses every name outside its own table with `unknown-agent`.
func skillAgent(row agentcatalog.Agent) string {
	if row.Skills != nil {
		return row.Name
	}
	return sharedSkillAgent
}

// skillEnv names the step variable carrying the skill-install agent. A row that
// installs into the shared directory gets its own variable: one workflow never
// spells VERDICT_AGENT twice with two different meanings.
func skillEnv(opts *renderOptions) string {
	if opts.skillAgent == opts.agent {
		return "VERDICT_AGENT"
	}
	return "VERDICT_SKILL_AGENT"
}

func firstNonEmpty(values ...string) string {
	for _, value := range values {
		if value != "" {
			return value
		}
	}
	return ""
}

// launchNames lists the agents a generated workflow can launch, for the
// unknown-agent refusal.
func launchNames() string {
	var names []string
	for _, row := range agentcatalog.All() {
		if row.Launch != nil {
			names = append(names, row.Name)
		}
	}
	return strings.Join(names, ", ")
}

// runnerHint opens the agent step with the prerequisite verdict cannot supply:
// the runner must already hold the agent's CLI, because the workflow installs
// verdict and never downloads a third-party agent. The catalog's install
// command rides along as a commented hint — pinning it, or replacing it with a
// runner image that ships the CLI, stays the operator's decision, and this
// generator executes no installer of its own.
func runnerHint(opts *renderOptions) string {
	hint := fmt.Sprintf("          # Install %s on the runner before this step: verdict installs\n"+
		"          # itself and never downloads an agent CLI.\n", opts.agent)
	if opts.install == "" {
		return hint
	}
	return hint + "          #   " + opts.install + "\n"
}

// permissionComment is the agent's documented permission flag as a comment:
// verdict never bakes a permission bypass into the agent's argv (STA-463).
func permissionComment(hint string) string {
	if hint == "" {
		return "          # This agent has no documented permission flag.\n"
	}
	return "          # verdict never bakes a permission flag: this agent's documented one is " +
		hint + ",\n          # appended by you inside agent_args when the run needs it.\n"
}

// renderWorkflow renders the every-PR workflow: pinned checkout and install
// steps, then the pipeline in the order the gate requires (post before gate).
func renderWorkflow(ci ciProvider, opts *renderOptions) []byte {
	body := fmt.Appendf(nil, workflowTemplate,
		ci.vars.permissions, ci.vars.pr, ci.vars.jobPermissions, ci.vars.forkGuard,
		CheckoutPin, CheckoutVersion, ci.vars.install,
		skillEnv(opts), opts.skillAgent,
		ci.vars.repository, ci.vars.pr, ci.vars.hostEnv, ci.vars.fetchFlag,
		ci.vars.readyStep, opts.agent, ci.vars.agentClear, opts.keyEnv, opts.keySecret,
		runnerHint(opts), permissionComment(opts.permission), opts.modelFlag,
	)
	return append([]byte(ci.header()), body...)
}

// workflowTemplate's verbs, in order: the two permission blocks, the PR number
// expression, the job-level fork guard, the checkout pin and the release it
// names, the install step, the skill step's variable and value, the repository
// expression, the fetch flag and readiness step, the agent name, the cleared
// tokens, the agent's key variable and its repository secret, the runner
// prerequisite, the permission comment, and the model flag.
const workflowTemplate = `
name: verdict review

on:
  pull_request:
    types: [opened, synchronize, reopened]

%[1]sconcurrency:
  group: verdict-%[2]s
  cancel-in-progress: true

jobs:
  review:
    name: review + merge gate
    runs-on: ubuntu-latest
    timeout-minutes: 30
%[3]s    # Fork pull requests get no repository secrets and a read-only token, so
    # the agent step cannot start there. Remove this line only to opt in with
    # a token and key you control for untrusted code. A skipped job reads as a
    # pass to branch protection.
    if: %[4]s
    steps:
      - name: Checkout
        uses: actions/checkout@%[5]s # %[6]s
        with:
          # The review controls are read from the PR base commit
          # (git show <base>:<path>), so the checkout must hold it.
          fetch-depth: 0
          persist-credentials: false

%[7]s
      - name: Install the review skill
        env:
          %[8]s: %[9]s
        shell: bash
        run: |
          verdict skill install --agent "$%[8]s"

      - name: Fetch the PR bundle
        env:
          VERDICT_REPOSITORY: %[10]s
          VERDICT_PR: %[11]s
%[12]s        shell: bash
        run: |
          verdict fetch "$VERDICT_REPOSITORY" "$VERDICT_PR"%[13]s
%[14]s
      - name: Agent review (verdict run --agent, your agent + your key)
        env:
          VERDICT_REPOSITORY: %[10]s
          VERDICT_PR: %[11]s
          VERDICT_AGENT: %[15]s
          VERDICT_MODEL: ${{ vars.VERDICT_MODEL }}
%[16]s          %[17]s: ${{ secrets.%[18]s }}
        shell: bash
        run: |
%[19]s%[20]s          agent_args=()
          if [ -n "${VERDICT_MODEL:-}" ]; then agent_args=(-- %[21]s "$VERDICT_MODEL"); fi
          verdict run "$VERDICT_REPOSITORY" "$VERDICT_PR" --agent "$VERDICT_AGENT" "${agent_args[@]}"

      - name: Post the review
        env:
          VERDICT_REPOSITORY: %[10]s
          VERDICT_PR: %[11]s
%[12]s        shell: bash
        run: |
          verdict post "$VERDICT_REPOSITORY" "$VERDICT_PR"

      - name: Review summary (advisory, never gates)
        env:
          VERDICT_REPOSITORY: %[10]s
          VERDICT_PR: %[11]s
%[12]s        shell: bash
        run: |
          verdict report "$VERDICT_REPOSITORY" "$VERDICT_PR"

      - name: Merge gate (findings + freshness + coverage + live threads)
        env:
          VERDICT_REPOSITORY: %[10]s
          VERDICT_PR: %[11]s
%[12]s        shell: bash
        run: |
          verdict gate "$VERDICT_REPOSITORY" "$VERDICT_PR" \
            --max-severity critical --require-head --live auto
`
