package initcore

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/stainless-code/verdict/internal/agentcatalog"
	"github.com/stainless-code/verdict/internal/core"
)

const (
	// workflowDir is workflowPath's parent directory.
	workflowDir = ".github/workflows"
	// workflowBase is the committed workflow's file name inside workflowDir.
	workflowBase = "verdict-review.yml"
	// workflowPath is the committed every-PR workflow, at the path
	// docs/ci-recipe.md names.
	workflowPath = workflowDir + "/" + workflowBase
	// workflowMode is the committed workflow's mode: nothing executes the file.
	workflowMode = 0o644
	// workflowHeader names the generator and its review obligation, and never
	// the build's version, so the bytes are identical across builds.
	workflowHeader = "# Generated by `verdict init --ci github`. Review before committing.\n" +
		"#\n" +
		"# Commit this file: every pull request then runs verdict on your runner with\n" +
		"# your agent and your own model key. Regenerate after upgrading verdict.\n"
	// defaultModelFlag is the argument an agent takes a model name on when its
	// catalog row names none.
	defaultModelFlag = "--model"
	// defaultAgent is the agent a --ci run wires when --agent names none.
	defaultAgent = "claude"
	// sharedSkillAgent is the skills directory every agent without one of its
	// own installs into: `verdict skill install --agent agents` is the only
	// name the installer accepts for those rows.
	sharedSkillAgent = "agents"
)

// keySecretName is the shape of one repository secret name. The name reaches a
// YAML env entry and a shell assignment, so anything looser is injection.
var keySecretName = regexp.MustCompile(`^[A-Z_][A-Z0-9_]*$`)

// renderOptions is the generated pipeline's per-agent half. keyEnv and
// keySecret are two names: the agent reads the first, the repository stores the
// key under the second. So `--key-secret REVIEW_KEY` on `claude` renders
// `ANTHROPIC_API_KEY: ${{ secrets.REVIEW_KEY }}`, never a `REVIEW_KEY:`
// variable claude does not read.
type renderOptions struct {
	agent      string
	skillAgent string
	keyEnv     string
	keySecret  string
	modelFlag  string
	permission string
	install    string
}

// workflowFor renders the workflow for the requested agent, or returns nil
// when the invocation is not a --ci run.
func (st *state) workflowFor() ([]byte, *core.RefusalError) {
	if st.req.CI == "" {
		return nil, nil
	}
	return RenderWorkflow(st.req.Agent, st.req.KeySecret)
}

// RenderWorkflow renders the every-PR workflow for one shipped agent name,
// taking the key secret from the catalog row unless keySecret names one. It is
// the byte contract the init tests and internal/archtest grade.
func RenderWorkflow(agent, keySecret string) ([]byte, *core.RefusalError) {
	opts, ref := wiredOptions(agent, keySecret)
	if ref != nil {
		return nil, ref
	}
	return renderWorkflow(&opts), nil
}

// wiredOptions resolves one agent name and secret name into render inputs. The
// secret defaults to the catalog row's documented key variable; a row that
// documents none needs an explicit --key-secret.
func wiredOptions(agent, keySecret string) (renderOptions, *core.RefusalError) {
	if keySecret != "" && !keySecretName.MatchString(keySecret) {
		return renderOptions{}, &core.RefusalError{
			Code: codeBadSettings,
			Message: fmt.Sprintf("invalid --key-secret '%s' "+
				"(want an env name like ANTHROPIC_API_KEY)", keySecret),
		}
	}
	row, ok := agentcatalog.Lookup(agent)
	if !ok || row.Launch == nil {
		return renderOptions{}, &core.RefusalError{
			Code:    codeUnknownAgent,
			Message: fmt.Sprintf("unknown agent '%s' (known: %s)", agent, launchNames()),
		}
	}
	secret := firstNonEmpty(keySecret, row.Launch.KeyEnv)
	if secret == "" {
		return renderOptions{}, &core.RefusalError{
			Code: codeBadSettings,
			Message: fmt.Sprintf("agent '%s' has no documented key variable; "+
				"pass --key-secret <NAME> naming the repository secret that holds its key", agent),
		}
	}
	return renderOptions{
		agent:      agent,
		skillAgent: skillAgent(row),
		keyEnv:     firstNonEmpty(row.Launch.KeyEnv, secret),
		keySecret:  secret,
		modelFlag:  firstNonEmpty(row.Launch.ModelFlag, defaultModelFlag),
		permission: row.Launch.PermissionHint,
		install:    row.Launch.Install,
	}, nil
}

// skillAgent is the name `verdict skill install` takes for this row: the agent
// itself when its catalog row declares a skills directory, else the shared
// agents directory. Most launchable rows declare none, and the installer
// refuses every name outside its own table with `unknown-agent`.
func skillAgent(row agentcatalog.Agent) string {
	if row.Skills != nil {
		return row.Name
	}
	return sharedSkillAgent
}

// skillEnv names the step variable carrying the skill-install agent. A row that
// installs into the shared directory gets its own variable: one workflow never
// spells VERDICT_AGENT twice with two different meanings.
func skillEnv(opts *renderOptions) string {
	if opts.skillAgent == opts.agent {
		return "VERDICT_AGENT"
	}
	return "VERDICT_SKILL_AGENT"
}

func firstNonEmpty(values ...string) string {
	for _, value := range values {
		if value != "" {
			return value
		}
	}
	return ""
}

// launchNames lists the agents a generated workflow can launch, for the
// unknown-agent refusal.
func launchNames() string {
	var names []string
	for _, row := range agentcatalog.All() {
		if row.Launch != nil {
			names = append(names, row.Name)
		}
	}
	return strings.Join(names, ", ")
}

// runnerHint opens the agent step with the prerequisite verdict cannot supply:
// the runner must already hold the agent's CLI, because the workflow installs
// verdict and never downloads a third-party agent. The catalog's install
// command rides along as a commented hint — pinning it, or replacing it with a
// runner image that ships the CLI, stays the operator's decision, and this
// generator executes no installer of its own.
func runnerHint(opts *renderOptions) string {
	hint := fmt.Sprintf("          # Install %s on the runner before this step: verdict installs\n"+
		"          # itself and never downloads an agent CLI.\n", opts.agent)
	if opts.install == "" {
		return hint
	}
	return hint + "          #   " + opts.install + "\n"
}

// permissionComment is the agent's documented permission flag as a comment:
// verdict never bakes a permission bypass into the agent's argv (STA-463).
func permissionComment(hint string) string {
	if hint == "" {
		return "          # This agent has no documented permission flag.\n"
	}
	return "          # verdict never bakes a permission flag: this agent's documented one is " +
		hint + ",\n          # appended by you inside agent_args when the run needs it.\n"
}

// renderWorkflow renders the every-PR workflow: pinned checkout and install
// steps, then the pipeline in the order the gate requires (post before gate).
func renderWorkflow(opts *renderOptions) []byte {
	body := fmt.Appendf(nil, workflowTemplate,
		CheckoutPin, CheckoutVersion, SetupVerdictPin, SetupVerdictVersion,
		opts.agent, opts.keyEnv, opts.keySecret, opts.modelFlag,
		runnerHint(opts), permissionComment(opts.permission),
		skillEnv(opts), opts.skillAgent,
	)
	return append([]byte(workflowHeader), body...)
}

// workflowTemplate's verbs, in order: the checkout pin and the release it
// names, the setup-verdict pin and its release, the agent name, the key
// variable the agent reads, the repository secret holding that key, the model
// flag, the runner prerequisite, the permission comment, and the skill step's
// variable and value.
const workflowTemplate = `
name: verdict review

on:
  pull_request:
    types: [opened, synchronize, reopened]

permissions:
  contents: read

concurrency:
  group: verdict-${{ github.event.pull_request.number }}
  cancel-in-progress: true

jobs:
  review:
    name: review + merge gate
    runs-on: ubuntu-latest
    timeout-minutes: 30
    permissions:
      contents: read
      pull-requests: write
    # Fork pull requests get no repository secrets and a read-only token, so
    # the agent step cannot start there. Remove this line only to opt in with
    # a token and key you control for untrusted code. A skipped job reads as a
    # pass to branch protection.
    if: github.event.pull_request.head.repo.full_name == github.repository
    steps:
      - name: Checkout
        uses: actions/checkout@%[1]s # %[2]s
        with:
          # The review controls are read from the PR base commit
          # (git show <base>:<path>), so the checkout must hold it.
          fetch-depth: 0
          persist-credentials: false

      - name: Install verdict
        uses: stainless-code/verdict/setup-verdict@%[3]s # %[4]s
        with:
          version: ${{ vars.VERDICT_VERSION }}

      - name: Install the review skill
        env:
          %[11]s: %[12]s
        shell: bash
        run: |
          verdict skill install --agent "$%[11]s"

      - name: Fetch the PR bundle
        env:
          VERDICT_REPOSITORY: ${{ github.repository }}
          VERDICT_PR: ${{ github.event.pull_request.number }}
          GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}
        shell: bash
        run: |
          verdict fetch "$VERDICT_REPOSITORY" "$VERDICT_PR"

      - name: Readiness pre-check (saves agent spend)
        env:
          VERDICT_REPOSITORY: ${{ github.repository }}
          VERDICT_PR: ${{ github.event.pull_request.number }}
          GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}
        shell: bash
        run: |
          verdict ready "$VERDICT_REPOSITORY" "$VERDICT_PR" --check

      - name: Agent review (verdict run --agent, your agent + your key)
        env:
          VERDICT_REPOSITORY: ${{ github.repository }}
          VERDICT_PR: ${{ github.event.pull_request.number }}
          VERDICT_AGENT: %[5]s
          VERDICT_MODEL: ${{ vars.VERDICT_MODEL }}
          GH_TOKEN: ""
          GITHUB_TOKEN: ""
          %[6]s: ${{ secrets.%[7]s }}
        shell: bash
        run: |
%[9]s%[10]s          agent_args=()
          if [ -n "${VERDICT_MODEL:-}" ]; then agent_args=(-- %[8]s "$VERDICT_MODEL"); fi
          verdict run "$VERDICT_REPOSITORY" "$VERDICT_PR" --agent "$VERDICT_AGENT" "${agent_args[@]}"

      - name: Post the review
        env:
          VERDICT_REPOSITORY: ${{ github.repository }}
          VERDICT_PR: ${{ github.event.pull_request.number }}
          GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}
        shell: bash
        run: |
          verdict post "$VERDICT_REPOSITORY" "$VERDICT_PR"

      - name: Review summary (advisory, never gates)
        env:
          VERDICT_REPOSITORY: ${{ github.repository }}
          VERDICT_PR: ${{ github.event.pull_request.number }}
          GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}
        shell: bash
        run: |
          verdict report "$VERDICT_REPOSITORY" "$VERDICT_PR"

      - name: Merge gate (findings + freshness + coverage + live threads)
        env:
          VERDICT_REPOSITORY: ${{ github.repository }}
          VERDICT_PR: ${{ github.event.pull_request.number }}
          GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}
        shell: bash
        run: |
          verdict gate "$VERDICT_REPOSITORY" "$VERDICT_PR" \
            --max-severity critical --require-head --live auto
`
