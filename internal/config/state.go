// State layout: the `.verdict` directory itself is never ignored. Only
// `/state/` is ignored through the nested file, so review state stays
// local while every control stays trackable. Legacy `.review/` is
// untouched: no migration, no rewrite, no shim.
//
// Writes never follow symlinks: `.verdict` may itself be a symlink in a
// PR working tree (config reads resolve through the trusted-base
// adapter), but state and ignore writes refuse a symlinked `.verdict`,
// `.verdict/state`, or `.verdict/.gitignore` instead of landing on an
// unrelated target, and the resolved paths must stay under the
// repository root. Reads never write: validation, explanation, and
// preview must not create files, shared or local.
const (
	// VerdictDir is the repository configuration directory at the Git root.
	VerdictDir = ".verdict"
	// ConfigPath is the one tracked typed configuration, at the Git root.
	ConfigPath = ".verdict/config.json"
	// KBPath is the tracked shared knowledge corpus beside the config.
	KBPath = ".verdict/kb.jsonl"
	// LearningsPath is the tracked shared heading memory.
	LearningsPath = ".verdict/learnings.md"
	// OverridesDir is the tracked shared override fragments directory.
	OverridesDir = ".verdict/overrides"
	// GitignorePath carries the tracked-shape `/state/`, `/backtest/`, and
	// `/index/` lines.
	GitignorePath = ".verdict/.gitignore"
	// StateDirName is the ignored local review state directory.
	StateDirName = "state"
	// StateGitignorePath pins a second ignore layer inside the state
	// directory: even a parent negation that names a generated file
	// cannot re-admit it, because the deeper `*` decides last.
	StateGitignorePath = ".verdict/state/.gitignore"
	// gitignoreStateLine, gitignoreBacktestLine, and gitignoreIndexLine are
	// the entire tracked ignore contract: review state, mined backtest
	// artifacts, and the local code index stay local.
	gitignoreStateLine    = "/state/\n"
	gitignoreBacktestLine = "/backtest/\n"
	gitignoreIndexLine    = "/index/\n"
	// stateGitignoreBody keeps every state file local no matter what a
	// parent ignore file negates.
	stateGitignoreBody = "# generated by verdict: everything under state/ stays local\n*\n"
	// stateDirPerm creates the configuration directory the ignore file
	// lives in.
	stateDirPerm = 0o755
)

// stateError is the package's sealed error type. State writes fail
// locally (permissions, storage); callers surface the message without
// inspecting the cause. Operator-caused failures (symlinked layouts,
// negated ignores, corrupt run bundles) set the operator flag so the
// caller maps them to the typed bad-config refusal instead of a local
// failure.
type stateError struct {
	cause error
	msg   string
	// operator marks failures the repository layout caused: the fix is an
	// operator edit, not a retry.
	operator bool
}

// Error implements error.
func (e *stateError) Error() string { return e.msg }

// Refusal maps an operator-caused state failure to the typed bad-config
// refusal; local failures map to nil so the caller wraps them with its
// own verb code.
func (e *stateError) Refusal() *core.RefusalError {
	if e == nil || !e.operator {
		return nil
	}
	return &core.RefusalError{Code: CodeBadConfig, Message: e.msg}
}

// Unwrap exposes the cause to [errors.Is]/[errors.As].
func (e *stateError) Unwrap() error { return e.cause }

// Layout resolves the state paths under one repository root.
type Layout struct {
	// Root is the Git root the layout was built for.
	Root string
}

// NewLayout builds the layout for root, defaulting empty root to the
// working directory.
func NewLayout(root string) Layout {
	if root == "" {
		root = "."
	}
	return Layout{Root: root}
}

// VerdictDir returns the configuration directory path.
func (l Layout) VerdictDir() string { return filepath.Join(l.Root, VerdictDir) }

// ConfigFile returns the tracked configuration path.
func (l Layout) ConfigFile() string { return filepath.Join(l.Root, ConfigPath) }

// StateDir returns the ignored local state directory path.
func (l Layout) StateDir() string {
	return filepath.Join(l.Root, VerdictDir, StateDirName)
}

// GitignoreFile returns the nested ignore file path.
func (l Layout) GitignoreFile() string { return filepath.Join(l.Root, GitignorePath) }

// msgBundleName refuses a bundle name that is not one path element. Every
// bundle verb renders this one line, so the refusal reads the same wherever a
// positional is wrong.
const msgBundleName = "bundle name must be one path element (a PR number or fetch-local name), not a path"

// The byte range a bundle name may not carry: the C0 controls and DEL, which
// no host or filesystem ever spells in a bundle's own name.
const (
	minControlByte = 0x20
	maxControlByte = 0x7f
)

// BundleDir joins one bundle name under root's bundle home. It refuses a name
// that is not exactly one path element, so no verb reads or writes outside the
// bundle home however its positional was spelled.
func BundleDir(root, name string) (string, *core.RefusalError) {
	if !validBundleName(name) {
		return "", &core.RefusalError{Code: CodeBadBundleName, Message: msgBundleName}
	}
	return filepath.Join(ifEmpty(root), VerdictDir, StateDirName, name), nil
}

// validBundleName reports whether name is exactly one path element that keeps
// its own spelling on every platform: joining it under the bundle home adds no
// level and lands nowhere else, and no other host's path rule reads it as a
// different name. A separator, dot-dot, the dot itself, an empty name, and a
// control byte refuse, as do the three spellings Windows re-reads: a colon
// (an alternate data stream or a volume-relative path), a trailing dot or
// space (trimmed, so `7.` is `7` and `.. ` is `..`), and a DOS device basename
// (`NUL`, `CON`, `PRN`, `AUX`, `COM1`-`COM9`, `LPT1`-`LPT9`, also before a
// dot), which opens the device instead of the bundle. Every rule applies on
// every OS, so one operator spelling refuses everywhere.
func validBundleName(name string) bool {
	if !filepath.IsLocal(name) || strings.ContainsAny(name, `/\`) || strings.ContainsRune(name, ':') {
		return false
	}
	if strings.HasSuffix(name, ".") || strings.HasSuffix(name, " ") || reservedBundleName(name) {
		return false
	}
	for i := range len(name) {
		if name[i] < minControlByte || name[i] == maxControlByte {
			return false
		}
	}
	return true
}

// reservedBundleName reports whether name is a DOS device name, which Windows
// resolves in every directory and before any extension: `NUL` and `nul.txt`
// both name the device.
func reservedBundleName(name string) bool {
	base, _, _ := strings.Cut(name, ".")
	switch strings.ToUpper(base) {
	case "CON", "PRN", "AUX", "NUL":
		return true
	}
	if len(base) != len("COM1") {
		return false
	}
	prefix := strings.ToUpper(base[:len("COM")])
	return (prefix == "COM" || prefix == "LPT") && base[len("COM")] >= '1' && base[len("COM")] <= '9'
}

// EnsureStateIgnore creates the `.verdict` directory and its `.gitignore`
// with the `/state/`, `/backtest/`, and `/index/` lines before any generated
// file is written, so review state, mined artifacts, and the local index are
// never tracked. It never
// runs on reads: validation, explanation, and preview paths must not create
// files, shared or local. An existing ignore file is preserved, gaining each
// line only when missing; a negation that re-admits `state` refuses loudly
// naming the line instead of being silently honored.
func (l Layout) EnsureStateIgnore() *stateError {
	root, serr := confineRoot(l.Root)
	if serr != nil {
		return serr
	}
	if serr := ensureManagedDir(root, VerdictDir); serr != nil {
		return serr
	}
	ignorePath, serr := confineJoin(root, GitignorePath)
	if serr != nil {
		return serr
	}
	if serr := refuseSymlinkLeaf(ignorePath, GitignorePath); serr != nil {
		return serr
	}
	return ensureStateLine(ignorePath)
}

// ensureStateLine writes the `/state/`, `/backtest/`, and `/index/`
// lines into an existing or absent ignore file. A negation able to
// re-admit state refuses naming the line instead of being silently honored
// or overwritten.
func ensureStateLine(ignorePath string) *stateError {
	raw, err := os.ReadFile(ignorePath)
	if errors.Is(err, os.ErrNotExist) {
		if werr := atomic.WriteFile(ignorePath, []byte(gitignoreStateLine+gitignoreBacktestLine+gitignoreIndexLine)); werr != nil {
			return &stateError{msg: "could not write " + ignorePath, cause: werr}
		}
		return nil
	}
	if err != nil {
		return &stateError{msg: "could not read " + ignorePath, cause: err}
	}
	if line, bad := conflictingStateNegation(string(raw)); bad {
		return &stateError{msg: ignorePath + " negates the state ignore with " + line + ": remove the negation", operator: true}
	}
	return writeIgnoreLines(ignorePath, raw)
}

// writeIgnoreLines appends each missing artifact line, preserving the file's
// existing bytes and its trailing-newline contract.
func writeIgnoreLines(ignorePath string, raw []byte) *stateError {
	var err error
	for _, want := range []string{gitignoreStateLine, gitignoreBacktestLine, gitignoreIndexLine} {
		if raw, err = ensureIgnoreLine(ignorePath, raw, want); err != nil {
			return &stateError{msg: "could not write " + ignorePath, cause: err}
		}
	}
	return nil
}

// ensureIgnoreLine returns raw with want appended when no equivalent line is
// present, writing the result atomically.
func ensureIgnoreLine(ignorePath string, raw []byte, want string) ([]byte, error) {
	if hasIgnoreLine(string(raw), want) {
		return raw, nil
	}
	if len(raw) > 0 && raw[len(raw)-1] != '\n' {
		raw = append(raw, '\n')
	}
	raw = append(raw, want...)
	if err := atomic.WriteFile(ignorePath, raw); err != nil {
		return nil, err
	}
	return raw, nil
}

// ensureManagedDir resolves one managed repository-relative directory,
// proves it stays anchored inside the root, refuses a symlinked leaf,
// and creates it: every managed write goes through this one gate.
func ensureManagedDir(root, name string) *stateError {
	full, serr := confineJoin(root, name)
	if serr != nil {
		return serr
	}
	if serr := refuseSymlinkLeaf(full, name); serr != nil {
		return serr
	}
	if err := os.MkdirAll(full, stateDirPerm); err != nil {
		return &stateError{msg: "could not create " + full, cause: err}
	}
	return nil
}

// EnsureStateDir creates the ignored local state directory with its
// second ignore layer, after EnsureStateIgnore. The nested `*` keeps
// every generated state file local even against parent negations that
// name generated files. The layer file is generated-local, so a
// divergent one is rewritten rather than merged.
func (l Layout) EnsureStateDir() *stateError {
	root, serr := confineRoot(l.Root)
	if serr != nil {
		return serr
	}
	if serr := ensureManagedDir(root, VerdictDir); serr != nil {
		return serr
	}
	stateName := filepath.Join(VerdictDir, StateDirName)
	if serr := ensureManagedDir(root, stateName); serr != nil {
		return serr
	}
	layer, serr := confineJoin(root, StateGitignorePath)
	if serr != nil {
		return serr
	}
	if serr := refuseSymlinkLeaf(layer, StateGitignorePath); serr != nil {
		return serr
	}
	return ensureStateLayer(layer)
}

// ensureStateLayer writes the generated-local nested `*` layer, which is
// ours rather than operator content: a divergent one is rewritten.
func ensureStateLayer(layer string) *stateError {
	raw, err := os.ReadFile(layer)
	if err == nil && string(raw) == stateGitignoreBody {
		return nil
	}
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return &stateError{msg: "could not read " + layer, cause: err}
	}
	if werr := atomic.WriteFile(layer, []byte(stateGitignoreBody)); werr != nil {
		return &stateError{msg: "could not write " + layer, cause: werr}
	}
	return nil
}

// confineRoot resolves the repository root to its real path: writes
// anchor below this directory and never above it.
func confineRoot(root string) (string, *stateError) {
	abs, err := filepath.Abs(root)
	if err != nil {
		return "", &stateError{msg: "could not resolve repository root " + root, cause: err}
	}
	resolvedRoot, err := filepath.EvalSymlinks(abs)
	if err != nil {
		return "", &stateError{msg: "could not resolve repository root " + root, cause: err}
	}
	return resolvedRoot, nil
}

// confineJoin joins a repository-relative path under the resolved root
// and proves the longest existing prefix resolves back inside the root:
// a symlink anywhere on the path that escapes the repository refuses
// instead of writing outside it.
func confineJoin(root, name string) (string, *stateError) {
	full := filepath.Join(root, name)
	prefix, rest, serr := existingPrefix(name, full)
	if serr != nil {
		return "", serr
	}
	if serr := checkAnchored(root, prefix, name, rest); serr != nil {
		return "", serr
	}
	return full, nil
}

// existingPrefix walks up from full until a path can be inspected,
// returning that prefix and the missing tail below it in reverse order.
// A symlink on the existing part is left for checkAnchored to resolve.
func existingPrefix(name, full string) (string, []string, *stateError) {
	prefix := full
	var rest []string
	for {
		_, err := os.Lstat(prefix)
		if err == nil {
			return prefix, rest, nil
		}
		if !errors.Is(err, os.ErrNotExist) {
			return "", nil, &stateError{msg: "could not inspect " + name, cause: err}
		}
		parent := filepath.Dir(prefix)
		if parent == prefix {
			return "", nil, &stateError{msg: "could not resolve " + name}
		}
		rest = append(rest, filepath.Base(prefix))
		prefix = parent
	}
}

// checkAnchored proves an existing prefix plus the missing tail resolves
// back inside the repository root.
func checkAnchored(root, prefix, name string, rest []string) *stateError {
	resolved, err := filepath.EvalSymlinks(prefix)
	if err != nil {
		return &stateError{msg: "could not resolve " + name, cause: err}
	}
	anchored := resolved
	for _, r := range slices.Backward(rest) {
		anchored = filepath.Join(anchored, r)
	}
	rel, err := filepath.Rel(root, anchored)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return &stateError{msg: "refuses to write outside the repository: " + name, operator: true}
	}
	return nil
}

// refuseSymlinkLeaf refuses to read or write through a symlinked managed
// path: the link target is an unrelated location even when it resolves
// inside the repository.
func refuseSymlinkLeaf(full, name string) *stateError {
	info, err := os.Lstat(full)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return &stateError{msg: "could not inspect " + name, cause: err}
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return &stateError{msg: name + " is a symlink: refusing to write through it", operator: true}
	}
	return nil
}

// conflictingStateNegation reports the first ignore line that negates the
// state exclusion. Only negations able to match the `state` directory
// itself refuse: broader file negations stay preserved, and the nested
// `*` layer still holds generated files ignored against them.
func conflictingStateNegation(raw string) (string, bool) {
	for _, line := range splitIgnoreLines(raw) {
		if isStateNegation(line) {
			return line, true
		}
	}
	return "", false
}

// trimDepthPrefixes strips every leading `**/` segment: gitignore's
// at-any-depth marker may repeat.
func trimDepthPrefixes(pattern string) string {
	for strings.HasPrefix(pattern, "**/") {
		pattern = strings.TrimPrefix(pattern, "**/")
	}
	return pattern
}

// isStateNegation matches `!`-lines whose pattern can match the state
// directory: the bare `state` name in any anchored or basename form,
// `state/`-prefixed paths, `*`-style globs matching `state`, and the
// match-everything `**`.
func isStateNegation(line string) bool {
	trimmed := strings.TrimSpace(line)
	if !strings.HasPrefix(trimmed, "!") {
		return false
	}
	pattern := strings.TrimSpace(strings.TrimPrefix(trimmed, "!"))
	// Both slashes go first: a trailing one would leave the depth strip with
	// an empty remainder (`**/`) and hide a match-all negation.
	pattern = strings.Trim(pattern, "/")
	// `**/` is gitignore for "at any depth" and may repeat, so every leading
	// segment is stripped first: `!**/state` and `!**/**/state` re-admit the
	// state directory exactly as `!state` would.
	pattern = trimDepthPrefixes(pattern)
	if pattern == "" {
		return false
	}
	if pattern == "**" {
		return true
	}
	if !strings.Contains(pattern, ignoreSeparator) {
		matched, err := path.Match(pattern, StateDirName)
		return err == nil && matched
	}
	if strings.HasPrefix(pattern, StateDirName+ignoreSeparator) {
		return true
	}
	matched, err := path.Match(pattern, StateDirName)
	return err == nil && matched
}

// ignoreSeparator is the gitignore path separator, always a slash.
const ignoreSeparator = "/"

// hasIgnoreLine reports whether one ignore line is already present, in any
// anchored or bare spelling git treats the same.
func hasIgnoreLine(raw, want string) bool {
	trimmed := strings.Trim(strings.TrimSpace(want), ignoreSeparator)
	for _, line := range splitIgnoreLines(raw) {
		if strings.Trim(line, ignoreSeparator) == trimmed {
			return true
		}
	}
	return false
}

// splitIgnoreLines splits on newlines, trimming trailing carriage
// returns and whitespace.
func splitIgnoreLines(raw string) []string {
	var out []string
	start := 0
	for i := 0; i <= len(raw); i++ {
		if i == len(raw) || raw[i] == '\n' {
			line := raw[start:i]
			line = trimRight(line)
			out = append(out, line)
			start = i + 1
		}
	}
	return out
}

// trimRight strips trailing spaces, tabs, and carriage returns.
func trimRight(s string) string {
	for len(s) > 0 && (s[len(s)-1] == ' ' || s[len(s)-1] == '\t' || s[len(s)-1] == '\r') {
		s = s[:len(s)-1]
	}
	return s
}
