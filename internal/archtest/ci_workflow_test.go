const (
	// runHeader opens a step's script block; runIndent is the indentation
	// GitHub strips before handing the body to bash.
	runHeader = "        run: |"
	runIndent = "          "
	// agentStepName is the one step that launches the operator's agent, so it
	// is where every injected write token must be cleared.
	agentStepName = "Agent review (verdict run --agent, your agent + your key)"
)

var (
	// usesPin matches one pinned action step: a full 40-hex commit SHA and the
	// release its trailing comment names, never a moving tag. Both the
	// short-form and the fully-qualified URL form are accepted.
	usesPin   = regexp.MustCompile(`^        uses: ([A-Za-z0-9_./:-]+)@([0-9a-f]{40}) # (v[0-9][0-9.]*)$`)
	stepName  = regexp.MustCompile(`^      - name: (.*)$`)
	secretEnv = regexp.MustCompile(`^          [A-Z_][A-Z0-9_]*: \$\{\{ secrets\.[A-Z_][A-Z0-9_]* \}\}$`)
)

// generatedWorkflowHead is the first line a provider's `--ci` run writes: the
// operator record, carrying no build version so every build renders it alike.
func generatedWorkflowHead(ci string) string {
	return "# Generated by `verdict init --ci " + ci + "`. Review before committing."
}

// generatedWorkflow renders the default workflow the named `--ci` path writes.
func generatedWorkflow(t *testing.T, ci string) string {
	t.Helper()
	body, ref := initcore.RenderWorkflow(ci, "claude", "")
	if ref != nil {
		t.Fatalf("render --ci %s: %s: %s", ci, ref.Code, ref.Message)
	}
	if len(body) == 0 {
		t.Fatalf("rendered --ci %s workflow is empty", ci)
	}
	return string(body)
}

// TestGeneratedWorkflowPinsMatchShippedActions proves the generator cannot
// drift from the shipped composite Action and example: the pins it renders are
// the very constants action.yml and examples/verdict-review.yml carry. The
// Forgejo install step is fully qualified because a short-form reference
// resolves through DEFAULT_ACTIONS_URL, which does not mirror this repository.
func TestGeneratedWorkflowPinsMatchShippedActions(t *testing.T) {
	t.Parallel()
	root := moduleRoot(t)
	for _, ci := range initcore.Providers() {
		workflow := generatedWorkflow(t, ci.Name())
		assertUsesLines(t, ci.Name()+" workflow", workflow)
		assertLineIn(t, ci.Name()+" workflow", workflow,
			"        uses: actions/checkout@"+initcore.CheckoutPin+" # "+initcore.CheckoutVersion)
	}
	github := generatedWorkflow(t, "github")
	assertLineIn(t, "github workflow", github,
		"        uses: stainless-code/verdict/setup-verdict@"+
			initcore.SetupVerdictPin+" # "+initcore.SetupVerdictVersion)
	forgejo := generatedWorkflow(t, "forgejo")
	assertLineIn(t, "forgejo workflow", forgejo,
		"        uses: https://github.com/stainless-code/verdict/setup-verdict@"+
			initcore.SetupVerdictPin+" # "+initcore.SetupVerdictVersion)
	action := readRepoFile(t, root, "action.yml")
	assertLineIn(t, "action.yml", action,
		"      uses: stainless-code/verdict/setup-verdict@"+initcore.SetupVerdictPin+" # "+initcore.SetupVerdictVersion)
	example := readRepoFile(t, root, filepath.Join("examples", "verdict-review.yml"))
	assertLineIn(t, "examples/verdict-review.yml", example,
		"        uses: actions/checkout@"+initcore.CheckoutPin+" # "+initcore.CheckoutVersion)
	assertLineIn(t, "examples/verdict-review.yml", example,
		"        uses: stainless-code/verdict@"+initcore.SetupVerdictPin+" # "+initcore.SetupVerdictVersion)
}

// TestGeneratedWorkflowShape pins each provider's top-level contract: the
// pull_request event, the supersede group, the job budget, and the fork guard
// with the consequence it documents. GitHub keeps both permission blocks; the
// Forgejo render carries neither, because Forgejo has no such key and an inert
// block would read as a security control it is not.
func TestGeneratedWorkflowShape(t *testing.T) {
	t.Parallel()
	for _, provider := range initcore.Providers() {
		assertGeneratedShape(t, provider.Name())
	}
}

// generatedShapeLines is the top-level contract every provider shares.
var generatedShapeLines = []string{
	"on:",
	"  pull_request:",
	"    types: [opened, synchronize, reopened]",
	"concurrency:",
	"  group: verdict-${{ github.event.pull_request.number }}",
	"  cancel-in-progress: true",
	"jobs:",
	"  review:",
	"    name: review + merge gate",
	"    runs-on: ubuntu-latest",
	generatedForkGuard,
	"    # pass to branch protection.",
}

// assertGeneratedShape pins one provider's top-level contract.
func assertGeneratedShape(t *testing.T, ci string) {
	t.Helper()
	workflow := generatedWorkflow(t, ci)
	assertGeneratedHeader(t, ci, workflow)
	for _, want := range generatedShapeLines {
		assertLineIn(t, ci+" workflow", workflow, want)
	}
	assertNoPullRequestTarget(t, ci, workflow)
	assertJobBudget(t, ci, workflow)
	assertGeneratedPermissions(t, ci, workflow)
}

// assertGeneratedHeader pins the first line's provider name.
func assertGeneratedHeader(t *testing.T, ci, workflow string) {
	t.Helper()
	first, _, _ := strings.Cut(workflow, "\n")
	if want := generatedWorkflowHead(ci); first != want {
		t.Fatalf("first line = %q, want %q", first, want)
	}
}

// assertNoPullRequestTarget refuses the trigger that would hand a fork's head
// the base repository's secrets.
func assertNoPullRequestTarget(t *testing.T, ci, workflow string) {
	t.Helper()
	if strings.Contains(workflow, "pull_request_target") {
		t.Fatalf("%s: the workflow runs on pull_request_target", ci)
	}
}

// assertGeneratedPermissions pins the one provider-specific top-level shape:
// GitHub keeps both permission blocks, Forgejo carries neither.
func assertGeneratedPermissions(t *testing.T, ci, workflow string) {
	t.Helper()
	if ci == "github" {
		assertGithubPermissions(t, workflow)
		return
	}
	assertForgejoShape(t, workflow)
}

// assertGithubPermissions pins both GitHub permission blocks.
func assertGithubPermissions(t *testing.T, workflow string) {
	t.Helper()
	for _, want := range []string{"permissions:", "  contents: read", "      pull-requests: write"} {
		assertLineIn(t, "github workflow", workflow, want)
	}
}

// assertForgejoShape pins what the Forgejo render must and must not carry.
func assertForgejoShape(t *testing.T, workflow string) {
	t.Helper()
	for _, forbidden := range []string{"permissions:", "Readiness pre-check"} {
		if strings.Contains(workflow, forbidden) {
			t.Fatalf("the Forgejo render carries %q", forbidden)
		}
	}
	for _, want := range []string{
		"          FORGEJO_HOST: ${{ github.server_url }}",
		"          FORGEJO_TOKEN: ${{ github.token }}",
		`          verdict fetch "$VERDICT_REPOSITORY" "$VERDICT_PR" --provider forgejo`,
	} {
		assertLineIn(t, "forgejo workflow", workflow, want)
	}
}

// assertJobBudget pins the generated job's literal timeout inside 1..60.
func assertJobBudget(t *testing.T, ci, workflow string) {
	t.Helper()
	const key = "    timeout-minutes: "
	for line := range strings.SplitSeq(workflow, "\n") {
		value, ok := strings.CutPrefix(line, key)
		if !ok {
			continue
		}
		minutes, err := strconv.Atoi(strings.TrimSpace(value))
		if err != nil || minutes < 1 || minutes > maxJobMinutes {
			t.Fatalf("%s: generated job declares timeout-minutes %q; want a literal 1..%d", ci, value, maxJobMinutes)
		}
		return
	}
	t.Fatalf("%s: generated job declares no timeout-minutes", ci)
}

