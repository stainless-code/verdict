// generatedWorkflowHead is the first line `verdict init --ci github` writes:
// the operator record, carrying no build version so every build renders it
// alike.
const generatedWorkflowHead = "# Generated by `verdict init --ci github`. Review before committing."

// generatedForkGuard is the job-level gate that keeps a fork PR from reaching a
// secret: the enforcement behind STA-465's untrusted-PR criterion.
const generatedForkGuard = "    if: github.event.pull_request.head.repo.full_name == github.repository"

// generatedStepNames is the generated job's step order, literally.
var generatedStepNames = []string{
	"Checkout",
	"Install verdict",
	"Install the review skill",
	"Fetch the PR bundle",
	"Readiness pre-check (saves agent spend)",
	"Agent review (verdict run --agent, your agent + your key)",
	"Post the review",
	"Review summary (advisory, never gates)",
	"Merge gate (findings + freshness + coverage + live threads)",
}

// generatedPipeline is the verdict verb order: post precedes the gate, whose
// --require-head and coverage dimensions read the receipt post writes.
var generatedPipeline = []string{
	`verdict skill install --agent "$VERDICT_AGENT"`,
	`verdict fetch "$VERDICT_REPOSITORY" "$VERDICT_PR"`,
	`verdict ready "$VERDICT_REPOSITORY" "$VERDICT_PR" --check`,
	`verdict run "$VERDICT_REPOSITORY" "$VERDICT_PR" --agent "$VERDICT_AGENT" "${agent_args[@]}"`,
	`verdict post "$VERDICT_REPOSITORY" "$VERDICT_PR"`,
	`verdict report "$VERDICT_REPOSITORY" "$VERDICT_PR"`,
	`verdict gate "$VERDICT_REPOSITORY" "$VERDICT_PR" \`,
}

const (
	// runHeader opens a step's script block; runIndent is the indentation
	// GitHub strips before handing the body to bash.
	runHeader = "        run: |"
	runIndent = "          "
)

var (
	// usesPin matches one pinned action step: a full 40-hex commit SHA and the
	// release its trailing comment names, never a moving tag.
	usesPin   = regexp.MustCompile(`^        uses: ([A-Za-z0-9_./-]+)@([0-9a-f]{40}) # (v[0-9][0-9.]*)$`)
	stepName  = regexp.MustCompile(`^      - name: (.*)$`)
	secretEnv = regexp.MustCompile(`^          [A-Z_][A-Z0-9_]*: \$\{\{ secrets\.[A-Z_][A-Z0-9_]* \}\}$`)
)

// generatedWorkflow renders the default workflow the `--ci github` path writes.
func generatedWorkflow(t *testing.T) string {
	t.Helper()
	body, ref := initcore.RenderWorkflow("claude", "")
	if ref != nil {
		t.Fatalf("render --ci github: %s: %s", ref.Code, ref.Message)
	}
	if len(body) == 0 {
		t.Fatal("rendered workflow is empty")
	}
	return string(body)
}

// TestGeneratedWorkflowPinsMatchShippedActions proves the generator cannot
// drift from the shipped composite Action and example: the pins it renders are
// the very constants action.yml and examples/verdict-review.yml carry.
func TestGeneratedWorkflowPinsMatchShippedActions(t *testing.T) {
	t.Parallel()
	root := moduleRoot(t)
	workflow := generatedWorkflow(t)
	assertUsesLines(t, "generated workflow", workflow)
	assertLineIn(t, "generated workflow", workflow,
		"        uses: actions/checkout@"+initcore.CheckoutPin+" # "+initcore.CheckoutVersion)
	assertLineIn(t, "generated workflow", workflow,
		"        uses: stainless-code/verdict/setup-verdict@"+initcore.SetupVerdictPin+" # "+initcore.SetupVerdictVersion)
	action := readRepoFile(t, root, "action.yml")
	assertLineIn(t, "action.yml", action,
		"      uses: stainless-code/verdict/setup-verdict@"+initcore.SetupVerdictPin+" # "+initcore.SetupVerdictVersion)
	example := readRepoFile(t, root, filepath.Join("examples", "verdict-review.yml"))
	assertLineIn(t, "examples/verdict-review.yml", example,
		"        uses: actions/checkout@"+initcore.CheckoutPin+" # "+initcore.CheckoutVersion)
	assertLineIn(t, "examples/verdict-review.yml", example,
		"        uses: stainless-code/verdict@"+initcore.SetupVerdictPin+" # "+initcore.SetupVerdictVersion)
}

// TestGeneratedWorkflowShape pins the top-level contract: the pull_request
// event, least-privilege permissions, the supersede group, the job budget, and
// the fork guard with the consequence it documents.
func TestGeneratedWorkflowShape(t *testing.T) {
	t.Parallel()
	workflow := generatedWorkflow(t)
	first, _, _ := strings.Cut(workflow, "\n")
	if first != generatedWorkflowHead {
		t.Fatalf("first line = %q, want %q", first, generatedWorkflowHead)
	}
	for _, want := range []string{
		"on:",
		"  pull_request:",
		"    types: [opened, synchronize, reopened]",
		"permissions:",
		"  contents: read",
		"concurrency:",
		"  group: verdict-${{ github.event.pull_request.number }}",
		"  cancel-in-progress: true",
		"jobs:",
		"  review:",
		"    name: review + merge gate",
		"    runs-on: ubuntu-latest",
		"      pull-requests: write",
		generatedForkGuard,
		"    # pass to branch protection.",
	} {
		assertLineIn(t, "generated workflow", workflow, want)
	}
	if strings.Contains(workflow, "pull_request_target") {
		t.Fatal("the workflow runs on pull_request_target: a fork's head would reach the base repo's secrets")
	}
	assertJobBudget(t, workflow)
}

// assertJobBudget pins the generated job's literal timeout inside 1..60.
func assertJobBudget(t *testing.T, workflow string) {
	t.Helper()
	const key = "    timeout-minutes: "
	for line := range strings.SplitSeq(workflow, "\n") {
		value, ok := strings.CutPrefix(line, key)
		if !ok {
			continue
		}
		minutes, err := strconv.Atoi(strings.TrimSpace(value))
		if err != nil || minutes < 1 || minutes > maxJobMinutes {
			t.Fatalf("generated job declares timeout-minutes %q; want a literal 1..%d", value, maxJobMinutes)
		}
		return
	}
	t.Fatal("generated job declares no timeout-minutes")
}

// TestGeneratedWorkflowStepOrder pins both orders literally: the step names,
// and the verdict verbs whose sequence the merge gate depends on.
func TestGeneratedWorkflowStepOrder(t *testing.T) {
	t.Parallel()
	workflow := generatedWorkflow(t)
	var names []string
	for line := range strings.SplitSeq(workflow, "\n") {
		if match := stepName.FindStringSubmatch(line); match != nil {
			names = append(names, match[1])
		}
	}
	if !slices.Equal(names, generatedStepNames) {
		t.Fatalf("step names = %q, want %q", names, generatedStepNames)
	}
	assertOrdered(t, workflow, generatedPipeline)
}

// TestGeneratedWorkflowKeepsSecretsOutOfShells proves no secret is written into
// a script: every secret is an env assignment the run bodies never interpolate,
// the agent step clears the write tokens, and no run body logs or traces a
// value.
func TestGeneratedWorkflowKeepsSecretsOutOfShells(t *testing.T) {
	t.Parallel()
	workflow := generatedWorkflow(t)
	assertSecretsStayInEnv(t, workflow)
	agent := generatedStepBlockOrFail(t, workflow, generatedStepNames[5])
	for _, want := range []string{
		`          GH_TOKEN: ""`,
		`          GITHUB_TOKEN: ""`,
		"          ANTHROPIC_API_KEY: ${{ secrets.ANTHROPIC_API_KEY }}",
		"          VERDICT_MODEL: ${{ vars.VERDICT_MODEL }}",
	} {
		assertLineIn(t, "agent step", agent, want)
	}
	assertRunBlocksCarryNoSecret(t, workflow)
}

// assertSecretsStayInEnv refuses a secret reference anywhere but an env
// assignment.
func assertSecretsStayInEnv(t *testing.T, workflow string) {
	t.Helper()
	for line := range strings.SplitSeq(workflow, "\n") {
		if strings.Contains(line, "secrets.") && !secretEnv.MatchString(line) {
			t.Errorf("secret reaches the workflow outside an env assignment: %s", line)
		}
	}
}

// assertRunBlocksCarryNoSecret refuses a run body that reads a secret, traces
// its shell, or dumps the environment.
func assertRunBlocksCarryNoSecret(t *testing.T, workflow string) {
	t.Helper()
	for _, block := range generatedRunBlocks(workflow) {
		for _, forbidden := range []string{"secrets.", "set -x", "printenv", "echo $"} {
			if strings.Contains(block, forbidden) {
				t.Errorf("run block carries %q:\n%s", forbidden, block)
			}
		}
	}
}

// TestGeneratedWorkflowRunsAreValidShell proves every run body is bash,
// offline: the extracted text must parse, which no byte comparison can show.
func TestGeneratedWorkflowRunsAreValidShell(t *testing.T) {
	t.Parallel()
	bash, err := exec.LookPath("bash")
	if err != nil {
		t.Fatal("bash is missing: the run bodies cannot be parsed")
	}
	blocks := generatedRunBlocks(generatedWorkflow(t))
	if len(blocks) != len(generatedPipeline) {
		t.Fatalf("run blocks = %d, want %d (one per pipeline step)", len(blocks), len(generatedPipeline))
	}
	dir := t.TempDir()
	for i, block := range blocks {
		path := filepath.Join(dir, "run-"+strconv.Itoa(i+1)+".sh")
		if err := os.WriteFile(path, []byte("#!/usr/bin/env bash\n"+block+"\n"), 0o600); err != nil {
			t.Fatal(err)
		}
		cmd := exec.CommandContext(t.Context(), bash, "-n", path)
		cmd.WaitDelay = 5 * time.Second
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Errorf("run block %d does not parse: %v\n%s\n%s", i+1, err, out, block)
		}
	}
}

// assertLineIn fails unless src carries want as a whole line.
func assertLineIn(t *testing.T, label, src, want string) {
	t.Helper()
	for line := range strings.SplitSeq(src, "\n") {
		if line == want {
			return
		}
	}
	t.Errorf("%s carries no line %q", label, want)
}

// assertUsesLines requires every uses: line to pin a 40-hex commit with a
// version comment, and at least one such line to exist.
func assertUsesLines(t *testing.T, label, workflow string) {
	t.Helper()
	count := 0
	for line := range strings.SplitSeq(workflow, "\n") {
		if !strings.HasPrefix(line, "        uses: ") {
			continue
		}
		count++
		if !usesPin.MatchString(line) {
			t.Errorf("%s: unpinned or moving-tag action: %s", label, line)
		}
	}
	if count == 0 {
		t.Fatalf("%s carries no uses: step", label)
	}
}

// assertOrdered fails unless every want appears in src in the given order.
func assertOrdered(t *testing.T, src string, wants []string) {
	t.Helper()
	at := 0
	for _, want := range wants {
		i := strings.Index(src[at:], want)
		if i < 0 {
			t.Fatalf("%q is absent or out of order", want)
		}
		at += i + len(want)
	}
}

// generatedStepBlock returns one step's lines, from its name to the next step.
func generatedStepBlock(workflow, name string) (string, bool) {
	lines := strings.Split(workflow, "\n")
	start := slices.Index(lines, "      - name: "+name)
	if start < 0 {
		return "", false
	}
	end := len(lines)
	for i, line := range lines[start+1:] {
		if strings.HasPrefix(line, "      - name: ") {
			end = start + 1 + i
			break
		}
	}
	return strings.Join(lines[start:end], "\n"), true
}

func generatedStepBlockOrFail(t *testing.T, workflow, name string) string {
	t.Helper()
	block, ok := generatedStepBlock(workflow, name)
	if !ok {
		t.Fatalf("no generated step named %q", name)
	}
	return block
}

// generatedRunBlocks returns each `run: |` body with its ten-space indent
// removed: the exact text GitHub hands bash.
func generatedRunBlocks(workflow string) []string {
	lines := strings.Split(workflow, "\n")
	var blocks []string
	for i := 0; i < len(lines); i++ {
		if lines[i] != runHeader {
			continue
		}
		body, next := runBody(lines, i+1)
		blocks = append(blocks, body)
		i = next - 1
	}
	return blocks
}

// runBody collects the indented lines after a `run: |` header, answering the
// body and the index of the first line that is not part of it.
func runBody(lines []string, start int) (string, int) {
	var body []string
	for i := start; i < len(lines); i++ {
		text, ok := strings.CutPrefix(lines[i], runIndent)
		if !ok {
			return strings.Join(body, "\n"), i
		}
		body = append(body, text)
	}
	return strings.Join(body, "\n"), len(lines)
}
