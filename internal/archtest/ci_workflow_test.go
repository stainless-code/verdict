// assertGeneratedStepOrder pins one provider's literal step names and verb
// order: post precedes the gate, whose dimensions read the receipt post writes.
func assertGeneratedStepOrder(t *testing.T, ci string) {
	t.Helper()
	workflow := generatedWorkflow(t, ci)
	if names, want := workflowStepNames(workflow), generatedStepNames[ci]; !slices.Equal(names, want) {
		t.Fatalf("step names = %q, want %q", names, want)
	}
	assertOrdered(t, workflow, generatedPipeline[ci])
}

// workflowStepNames answers one render's step names in order.
func workflowStepNames(workflow string) []string {
	var names []string
	for line := range strings.SplitSeq(workflow, "\n") {
		if match := stepName.FindStringSubmatch(line); match != nil {
			names = append(names, match[1])
		}
	}
	return names
}

// TestGeneratedWorkflowKeepsSecretsOutOfShells proves no expression is written
// into a script: every secret is an env assignment the run bodies never
// interpolate, the agent step clears the tokens its host injects, and no run
// body logs or traces a value.
func TestGeneratedWorkflowKeepsSecretsOutOfShells(t *testing.T) {
	t.Parallel()
	for _, provider := range initcore.Providers() {
		assertGeneratedSecretsStayOut(t, provider.Name())
	}
}

// assertGeneratedSecretsStayOut grades one provider's token carriers: every
// secret is an env assignment, no run body interpolates an expression, the
// agent step clears the tokens its host injects, and nothing traces a value.
func assertGeneratedSecretsStayOut(t *testing.T, ci string) {
	t.Helper()
	workflow := generatedWorkflow(t, ci)
	assertSecretsStayInEnv(t, ci, workflow)
	assertNoExpressionInRunBodies(t, ci, workflow)
	agent := generatedStepBlockOrFail(t, workflow, agentStepName)
	assertAgentClearsTokens(t, ci, agent)
	if ci == "forgejo" {
		assertForgejoFetchEnv(t, workflow)
	}
	assertRunBlocksCarryNoSecret(t, ci, workflow)
}

// assertAgentClearsTokens pins the token names the agent step must zero. The
// Forgejo render clears one more: the host injects FORGEJO_TOKEN as well.
func assertAgentClearsTokens(t *testing.T, ci, agent string) {
	t.Helper()
	want := []string{
		`          GH_TOKEN: ""`,
		`          GITHUB_TOKEN: ""`,
		"          ANTHROPIC_API_KEY: ${{ secrets.ANTHROPIC_API_KEY }}",
		"          VERDICT_MODEL: ${{ vars.VERDICT_MODEL }}",
	}
	if ci == "forgejo" {
		want = append(want, `          FORGEJO_TOKEN: ""`)
	}
	for _, line := range want {
		assertLineIn(t, "agent step", agent, line)
	}
}

// assertForgejoFetchEnv proves the fetch step speaks Forgejo's vocabulary only:
// FORGEJO_HOST/FORGEJO_TOKEN, with no GitHub token name left in it.
func assertForgejoFetchEnv(t *testing.T, workflow string) {
	t.Helper()
	fetch := generatedStepBlockOrFail(t, workflow, "Fetch the PR bundle")
	for _, want := range []string{
		"          FORGEJO_HOST: ${{ github.server_url }}",
		"          FORGEJO_TOKEN: ${{ github.token }}",
	} {
		assertLineIn(t, "fetch step", fetch, want)
	}
	if strings.Contains(fetch, "GH_TOKEN") {
		t.Fatalf("the Forgejo fetch step carries a GitHub token name:\n%s", fetch)
	}
}

// assertSecretsStayInEnv refuses a secret reference anywhere but an env
// assignment.
func assertSecretsStayInEnv(t *testing.T, ci, workflow string) {
	t.Helper()
	for line := range strings.SplitSeq(workflow, "\n") {
		if strings.Contains(line, "secrets.") && !secretEnv.MatchString(line) {
			t.Errorf("%s: secret reaches the workflow outside an env assignment: %s", ci, line)
		}
	}
}

// assertNoExpressionInRunBodies refuses an interpolated expression inside a
// script: the shell would read attacker-influenced text, and the env seam is
// the only supported carrier.
func assertNoExpressionInRunBodies(t *testing.T, ci, workflow string) {
	t.Helper()
	for _, block := range generatedRunBlocks(workflow) {
		if strings.Contains(block, "${{") {
			t.Errorf("%s: run block interpolates an expression:\n%s", ci, block)
		}
	}
}

// assertRunBlocksCarryNoSecret refuses a run body that reads a secret, traces
// its shell, or dumps the environment.
func assertRunBlocksCarryNoSecret(t *testing.T, ci, workflow string) {
	t.Helper()
	for _, block := range generatedRunBlocks(workflow) {
		for _, forbidden := range []string{"secrets.", "set -x", "printenv", "echo $"} {
			if strings.Contains(block, forbidden) {
				t.Errorf("%s: run block carries %q:\n%s", ci, forbidden, block)
			}
		}
	}
}

// TestGeneratedWorkflowRunsAreValidShell proves every run body is bash,
// offline: the extracted text must parse, which no byte comparison can show.
func TestGeneratedWorkflowRunsAreValidShell(t *testing.T) {
	t.Parallel()
	bash, err := exec.LookPath("bash")
	if err != nil {
		t.Fatal("bash is missing: the run bodies cannot be parsed")
	}
	for _, provider := range initcore.Providers() {
		assertRunBodiesParse(t, bash, provider.Name())
	}
}

// assertRunBodiesParse proves one provider's run bodies are bash, offline: the
// extracted text must parse, which no byte comparison can show.
func assertRunBodiesParse(t *testing.T, bash, ci string) {
	t.Helper()
	blocks := generatedRunBlocks(generatedWorkflow(t, ci))
	if want := len(generatedPipeline[ci]); len(blocks) != want {
		t.Fatalf("%s: run blocks = %d, want %d (one per pipeline step)", ci, len(blocks), want)
	}
	dir := t.TempDir()
	for i, block := range blocks {
		assertRunBodyParses(t, bash, dir, i, block)
	}
}

// assertRunBodyParses writes one run body and runs `bash -n` over it.
func assertRunBodyParses(t *testing.T, bash, dir string, index int, block string) {
	t.Helper()
	path := filepath.Join(dir, "run-"+strconv.Itoa(index+1)+".sh")
	if err := os.WriteFile(path, []byte("#!/usr/bin/env bash\n"+block+"\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	cmd := exec.CommandContext(t.Context(), bash, "-n", path)
	cmd.WaitDelay = 5 * time.Second
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Errorf("run block %d does not parse: %v\n%s\n%s", index+1, err, out, block)
	}
}

// assertLineIn fails unless src carries want as a whole line.
func assertLineIn(t *testing.T, label, src, want string) {
	t.Helper()
	for line := range strings.SplitSeq(src, "\n") {
		if line == want {
			return
		}
	}
	t.Errorf("%s carries no line %q", label, want)
}

// assertUsesLines requires every uses: line to pin a 40-hex commit with a
// version comment, and at least one such line to exist.
func assertUsesLines(t *testing.T, label, workflow string) {
	t.Helper()
	count := 0
	for line := range strings.SplitSeq(workflow, "\n") {
		if !strings.HasPrefix(line, "        uses: ") {
			continue
		}
		count++
		if !usesPin.MatchString(line) {
			t.Errorf("%s: unpinned or moving-tag action: %s", label, line)
		}
	}
	if count == 0 {
		t.Fatalf("%s carries no uses: step", label)
	}
}

// assertOrdered fails unless every want appears in src in the given order.
func assertOrdered(t *testing.T, src string, wants []string) {
	t.Helper()
	at := 0
	for _, want := range wants {
		i := strings.Index(src[at:], want)
		if i < 0 {
			t.Fatalf("%q is absent or out of order", want)
		}
		at += i + len(want)
	}
}

// generatedStepBlock returns one step's lines, from its name to the next step.
func generatedStepBlock(workflow, name string) (string, bool) {
	lines := strings.Split(workflow, "\n")
	start := slices.Index(lines, "      - name: "+name)
	if start < 0 {
		return "", false
	}
	end := len(lines)
	for i, line := range lines[start+1:] {
		if strings.HasPrefix(line, "      - name: ") {
			end = start + 1 + i
			break
		}
	}
	return strings.Join(lines[start:end], "\n"), true
}

func generatedStepBlockOrFail(t *testing.T, workflow, name string) string {
	t.Helper()
	block, ok := generatedStepBlock(workflow, name)
	if !ok {
		t.Fatalf("no generated step named %q", name)
	}
	return block
}

// generatedRunBlocks returns each `run: |` body with its ten-space indent
// removed: the exact text GitHub hands bash.
func generatedRunBlocks(workflow string) []string {
	lines := strings.Split(workflow, "\n")
	var blocks []string
	for i := 0; i < len(lines); i++ {
		if lines[i] != runHeader {
			continue
		}
		body, next := runBody(lines, i+1)
		blocks = append(blocks, body)
		i = next - 1
	}
	return blocks
}

// runBody collects the indented lines after a `run: |` header, answering the
// body and the index of the first line that is not part of it.
func runBody(lines []string, start int) (string, int) {
	var body []string
	for i := start; i < len(lines); i++ {
		text, ok := strings.CutPrefix(lines[i], runIndent)
		if !ok {
			return strings.Join(body, "\n"), i
		}
		body = append(body, text)
	}
	return strings.Join(body, "\n"), len(lines)
}
