#!/usr/bin/env node
// Render the Homebrew formula from dist/checksums.txt: per-OS/arch URL +
// sha256 blocks for the unix archives, `bin.install`, and a `test do`
// smoke. Writes the file, never pushes the tap.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPTS_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = dirname(SCRIPTS_DIR);

export function loadContract() {
  const path = join(REPO_ROOT, "release", "contract.json");
  return JSON.parse(readFileSync(path, "utf8"));
}

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (!arg.startsWith("--")) {
      throw new Error(`unexpected argument: ${arg}`);
    }
    const value = argv[i + 1];
    if (value === undefined || value.startsWith("--")) {
      throw new Error(`missing value for ${arg}`);
    }
    out[arg.slice(2)] = value;
    i++;
  }
  return out;
}

function parseChecksums(text) {
  const sums = new Map();
  for (const line of text.split("\n")) {
    if (line.trim() === "") {
      continue;
    }
    const match = /^([0-9a-f]{64})\s+(\S+)$/.exec(line.trim());
    if (!match) {
      throw new Error(`unparsable checksums line: ${line}`);
    }
    sums.set(match[2].split("/").pop(), match[1]);
  }
  return sums;
}

function archiveURL(contract, entry, version) {
  const ext = entry.file.endsWith(".zip") ? "zip" : "tar.gz";
  return contract.urls.archive
    .replaceAll("{version}", version)
    .replaceAll("{goos}", entry.goos)
    .replaceAll("{goarch}", entry.goarch)
    .replaceAll("{ext}", ext);
}

export function generateFormula(options) {
  const contract = loadContract();
  const dist = options.dist ?? join(REPO_ROOT, "dist");
  const sums = parseChecksums(
    readFileSync(options.checksums ?? join(dist, contract.checksums), "utf8"),
  );
  const unix = contract.archives.filter((entry) => entry.goos !== "windows");
  const byPlatform = new Map();
  let seen;
  for (const entry of unix) {
    const prefix = "verdict_";
    const suffix = `_${entry.goos}_${entry.goarch}.`;
    let match;
    for (const name of sums.keys()) {
      if (
        name.startsWith(prefix) &&
        name.includes(suffix) &&
        (name.endsWith(".tar.gz") || name.endsWith(".zip"))
      ) {
        if (match !== undefined) {
          throw new Error(
            `multiple checksums for ${entry.goos}/${entry.goarch}`,
          );
        }
        match = name;
      }
    }
    if (match === undefined) {
      throw new Error(`no checksum for ${entry.goos}/${entry.goarch}`);
    }
    const version = match.slice(prefix.length, match.indexOf(suffix));
    if (seen === undefined) {
      seen = version;
    } else if (seen !== version) {
      throw new Error(`mixed versions in checksums: ${version} vs ${seen}`);
    }
    byPlatform.set(`${entry.goos}/${entry.goarch}`, {
      entry,
      sha: sums.get(match),
    });
  }
  const version = options.version ?? seen;
  if (options.version !== undefined && options.version !== seen) {
    throw new Error(
      `checksums are v${seen}, refusing to render v${options.version}`,
    );
  }
  const block = (goos, goarch, indent) => {
    const found = byPlatform.get(`${goos}/${goarch}`);
    const pad = " ".repeat(indent);
    return (
      `${pad}url "${archiveURL(contract, found.entry, version)}"\n` +
      `${pad}sha256 "${found.sha}"\n`
    );
  };
  const formula = contract.formula;
  const text =
    "# frozen_string_literal: true\n" +
    "# Generated by scripts/generate-formula.mjs from dist/checksums.txt.\n" +
    "# Do not edit by hand; scripts/release.sh pushes the tap copy.\n" +
    `class ${formula.class} < Formula\n` +
    `  desc "${formula.desc}"\n` +
    `  homepage "${formula.homepage}"\n` +
    `  license "${formula.license}"\n` +
    `  version "${version}"\n` +
    "\n" +
    "  on_macos do\n" +
    "    on_intel do\n" +
    block("darwin", "amd64", 6) +
    "    end\n" +
    "    on_arm do\n" +
    block("darwin", "arm64", 6) +
    "    end\n" +
    "  end\n" +
    "\n" +
    "  on_linux do\n" +
    "    on_intel do\n" +
    block("linux", "amd64", 6) +
    "    end\n" +
    "    on_arm do\n" +
    block("linux", "arm64", 6) +
    "    end\n" +
    "  end\n" +
    "\n" +
    "  def install\n" +
    `    bin.install "${formula.installBin}"\n` +
    "  end\n" +
    "\n" +
    "  test do\n" +
    '    assert_match version.to_s, shell_output("#{bin}/verdict --version")\n' +
    "  end\n" +
    "end\n";
  const dest = options.out ?? join(dist, formula.path);
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, text);
  return { version, dest };
}

function main(argv) {
  const args = parseArgs(argv);
  const result = generateFormula({
    dist: args.dist,
    out: args.out,
    checksums: args.checksums,
    version: args.version,
  });
  process.stdout.write(`formula: wrote ${result.dest} (v${result.version})\n`);
}

try {
  if (process.argv[1] === fileURLToPath(import.meta.url)) {
    main(process.argv.slice(2));
  }
} catch (error) {
  process.stderr.write(`generate-formula: ${error.message}\n`);
  process.exit(1);
}
