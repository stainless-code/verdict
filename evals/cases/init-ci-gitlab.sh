#!/usr/bin/env bash
#
# `verdict init --ci gitlab`: the generated merge-request pipeline, its
# non-clobbering root file, the runtime token boundary, the --print shapes, and
# the documented anchors. Every host tool call is stubbed network-dead; init
# makes none.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=../lib/common.sh
. "$HERE/../lib/common.sh"
# shellcheck source=../lib/hoststub.sh
. "$HERE/../lib/hoststub.sh"

command -v shellcheck >/dev/null 2>&1 || bail "shellcheck is missing: the generated run blocks cannot be graded"

hoststub_init gh glab curl

WF_REL=".gitlab/ci/verdict-review.yml"
ROOT_REL=".gitlab-ci.yml"
HEADER='# Generated by `verdict init --ci gitlab`. Review before committing.'
RULE_LINE="    - if: '\$CI_PIPELINE_SOURCE == \"merge_request_event\" && \$CI_MERGE_REQUEST_SOURCE_PROJECT_PATH == \$CI_PROJECT_PATH'"
UNSET_LINE="        unset GITLAB_TOKEN GLAB_TOKEN GITLAB_ACCESS_TOKEN OAUTH_TOKEN CI_JOB_TOKEN GLAB_ENABLE_CI_AUTOLOGIN GH_TOKEN GITHUB_TOKEN"
INCLUDE_LINE="  - local: .gitlab/ci/verdict-review.yml"
SC_LOG="$EVAL_SANDBOX/ci-gitlab-shellcheck.txt"
: >"$SC_LOG"
stub_before="$(wc -l <"$EVAL_STUBLOG" | tr -d ' ')"

# ci_repo makes one clean repo sandbox with an initial commit.
ci_repo() { # $1 = dir
  mkdir -p "$1"
  (
    cd "$1" || exit 99
    git init -q
    git config user.email "init-ci@example.com"
    git config user.name "init ci"
    echo "probe" >probe.txt
    git add -A
    git commit -qm init
  )
}

# ci_init runs the CLI in dir, capturing EVAL_STATUS/EVAL_OUT/EVAL_ERR.
ci_init() { # $1 = dir, rest = init argv
  local dir="$1"
  shift
  EVAL_STATUS=0
  ( cd "$dir" && PATH="$EVAL_STUBBIN:$PATH" "$EVAL_CLI" "$@" >"$EVAL_OUT" 2>"$EVAL_ERR" ) || EVAL_STATUS=$?
}

REPO="$EVAL_SANDBOX/ci-gitlab-repo"
ci_repo "$REPO"
WF="$REPO/$WF_REL"
ROOT="$REPO/$ROOT_REL"

ci_init "$REPO" init --ci gitlab
assert_exit "init --ci gitlab writes both files" 0
if [ -f "$WF" ]; then
  good "the pipeline lands at $WF_REL"
else
  bad "the pipeline is missing at $WF_REL"
  bail "nothing to grade"
fi
if [ -f "$ROOT" ]; then
  good "the root pipeline is created when absent"
else
  bad "the root pipeline was not created"
fi

assert_eq "the pipeline's first line names the generator" "$HEADER" "$(head -1 "$WF")"
assert_eq "the root pipeline's first line carries the same header" "$HEADER" "$(head -1 "$ROOT")"
assert_file_grep "the pipeline is one job" "$WF" '^verdict-review:$'
assert_file_grep "the job lands in the default stage" "$WF" '^  stage: test$'
assert_eq "the merge-request rule carries the fork clause" "$RULE_LINE" \
  "$(grep -F -m1 'merge_request_event' "$WF")"
assert_file_grep "the clone keeps the history the controls are read from" "$WF" '^    GIT_DEPTH: "0"$'
assert_file_grep "the repository is the project path" "$WF" '^    VERDICT_REPOSITORY: \$CI_PROJECT_PATH$'
assert_file_grep "the merge request is the MR IID" "$WF" '^    VERDICT_PR: \$CI_MERGE_REQUEST_IID$'
assert_file_grep "the host keeps a nonstandard port" "$WF" '^    GITLAB_HOST: \$CI_SERVER_FQDN$'
assert_file_grep "the job declares its own timeout" "$WF" '^  timeout: 30 minutes$'
assert_file_grep "the job is interruptible" "$WF" '^  interruptible: true$'
assert_file_grep "the gate is the composed verb" "$WF" \
  '^        --max-severity critical --require-head --live auto$'
assert_file_grep "only the fetch block names the provider" "$WF" \
  '^      verdict fetch "\$VERDICT_REPOSITORY" "\$VERDICT_PR" --provider gitlab$'
assert_eq "the provider flag appears exactly once" "1" "$(grep -c -- '--provider gitlab' "$WF")"
assert_file_grep "the readiness pre-check is kept" "$WF" \
  '^      verdict ready "\$VERDICT_REPOSITORY" "\$VERDICT_PR" --check$'

assert_file_nogrep "the render is not an Actions workflow" "$WF" 'uses:'
assert_file_nogrep "the render carries no permissions block" "$WF" 'permissions:'
assert_file_nogrep "the render carries no top-level on:" "$WF" '^on:$'
assert_file_nogrep "the render carries no per-step env" "$WF" 'env:'
assert_file_nogrep "the render never mentions pull_request" "$WF" 'pull_request'
assert_file_nogrep "never traces the shell" "$WF" 'set -x'

assert_eq "the agent block empties glab's whole lookup order" "$UNSET_LINE" \
  "$(grep -F -m1 'unset GITLAB_TOKEN' "$WF")"
assert_file_grep "the token clear is a scoped subshell" "$WF" '^      ($'
assert_file_grep "the installer pins one release commit" "$WF" \
  'raw\.githubusercontent\.com/stainless-code/verdict/[0-9a-f]\{40\}/install\.sh'
scripted="$(grep -E 'install\.sh' "$WF" | grep -v -E '^ *#' || true)"
assert_eq "one install script actually runs" "1" "$(printf '%s\n' "$scripted" | grep -c . || true)"
assert_file_grep "the install script is the pinned verdict installer" "$WF" \
  'raw\.githubusercontent\.com/stainless-code/verdict/[0-9a-f]\{40\}/install\.sh'
assert_file_grep "the glab prerequisite is stated" "$WF" \
  '^    # Install glab on the runner before this pipeline: verdict installs itself$'
runs_glab="$(grep -nE 'glab (auth|install|api)' "$WF" | grep -v -E '^[0-9]+: *#' || true)"
assert_eq "no glab installer runs" "" "$runs_glab"
assert_file_nogrep "the default render names no model key" "$WF" 'ANTHROPIC_API_KEY'

assert_eq "the pipeline runs in the reviewed order" \
  "skill install|fetch|ready|run|post|report|gate" \
  "$(grep -oE '^ +verdict [a-z]+( install)?' "$WF" | sed -E 's/^ +verdict //' | paste -sd'|' -)"
if [ "$(grep -nE '^ +curl -fsSL' "$WF" | cut -d: -f1)" -lt \
  "$(grep -n 'verdict skill install' "$WF" | cut -d: -f1)" ]; then
  good "verdict is installed before the skill step reads it"
else
  bad "the skill step runs before verdict is installed"
fi

BLOCKS="$EVAL_SANDBOX/ci-gitlab-runs"
mkdir -p "$BLOCKS"
awk -v dir="$BLOCKS" '
  /^    - \|$/ { open=1; n++; f=sprintf("%s/run-%02d.sh", dir, n); print "#!/usr/bin/env bash" > f; next }
  open && /^      / { sub(/^      /, ""); print > f; next }
  { open=0 }
' "$WF"
problems=""
blocks=0
for block in "$BLOCKS"/run-*.sh; do
  blocks=$((blocks + 1))
  bash -n "$block" 2>>"$SC_LOG" || problems="$problems parse:$(basename "$block")"
  shellcheck -S warning "$block" >>"$SC_LOG" 2>&1 || problems="$problems shellcheck:$(basename "$block")"
  if grep -qF '${{' "$block"; then problems="$problems expression:$(basename "$block")"; fi
done
assert_eq "eight script blocks were extracted" "8" "$blocks"
assert_eq "every script block parses, checks, and interpolates nothing" "" "$problems"
if [ -s "$SC_LOG" ]; then
  bad "shellcheck reported on the generated script blocks: $(head -20 "$SC_LOG" | tr '\n' ' ')"
else
  good "shellcheck -S warning is silent on every generated script block"
fi

# The root pipeline is the generated header, one paragraph, and one include over
# the file that was just written.
cat >"$EVAL_SANDBOX/ci-gitlab-root-expected.yml" <<'ROOTEOF'
# Generated by `verdict init --ci gitlab`. Review before committing.
#
# Commit this file: every merge request then runs verdict on your runner with
# your agent and your own model key. Regenerate after upgrading verdict.

# One include, so this file stays yours to edit. Delete the include to turn
# the automatic review off; .gitlab/ci/verdict-review.yml is the pipeline.

include:
  - local: .gitlab/ci/verdict-review.yml
ROOTEOF
assert_file_eq "the root pipeline is exactly the include" \
  "$EVAL_SANDBOX/ci-gitlab-root-expected.yml" "$ROOT"
assert_eq "the include names the written pipeline" "$INCLUDE_LINE" "$(tail -1 "$ROOT")"
assert_file_grep "the route to the pipeline file exists" "$ROOT" "^  - local: $WF_REL\$"
assert_file_grep "the next line names both committed files" "$EVAL_OUT" \
  '^next: commit \.gitlab/ci/verdict-review\.yml and \.gitlab-ci\.yml with \.verdict/, '
assert_file_grep "the next line names the CI/CD variable store" "$EVAL_OUT" 'set the CI/CD variable VERDICT_VERSION'

cp "$WF" "$EVAL_SANDBOX/ci-gitlab-wf-copy.yml"
cp "$ROOT" "$EVAL_SANDBOX/ci-gitlab-root-copy.yml"
ci_init "$REPO" init --ci gitlab
assert_exit "a second run is idempotent" 0
if grep -q "keep: $WF_REL (already up to date)" "$EVAL_OUT" &&
  grep -q "keep: $ROOT_REL (already up to date)" "$EVAL_OUT"; then
  good "both identical files read as keep"
else
  bad "the idempotent re-run did not report keep for both files"
fi
assert_file_eq "the kept pipeline is byte-identical" "$EVAL_SANDBOX/ci-gitlab-wf-copy.yml" "$WF"
assert_file_eq "the kept root pipeline is byte-identical" "$EVAL_SANDBOX/ci-gitlab-root-copy.yml" "$ROOT"

# An operator-owned root pipeline is never touched, with or without --force.
for flag in "" "--force"; do
  OWNED="$EVAL_SANDBOX/ci-gitlab-root${flag:+-force}"
  ci_repo "$OWNED"
  printf 'stages: [build, deploy]\n' >"$OWNED/$ROOT_REL"
  (
    cd "$OWNED" || exit 99
    git add -A
    git commit -qm "seed root pipeline"
  )
  cp "$OWNED/$ROOT_REL" "$EVAL_SANDBOX/ci-gitlab-seed${flag:+-force}.yml"
  # shellcheck disable=SC2086 # an empty flag is the difference under test
  ci_init "$OWNED" init --ci gitlab $flag
  assert_exit "an existing root pipeline is reported, not refused (${flag:-no flag})" 0
  assert_file_eq "the operator's root pipeline is untouched (${flag:-no flag})" \
    "$EVAL_SANDBOX/ci-gitlab-seed${flag:+-force}.yml" "$OWNED/$ROOT_REL"
  assert_file_grep "the run says the root is present (${flag:-no flag})" "$EVAL_OUT" \
    "present: .gitlab-ci.yml (left untouched)" -F
  assert_file_grep "the run prints the include to add (${flag:-no flag})" "$EVAL_OUT" \
    "^  - local: $WF_REL\$"
  assert_file_grep "the next line hands the include to the operator (${flag:-no flag})" "$EVAL_OUT" \
    'add the include to \.gitlab-ci\.yml yourself'
  rm -rf "$OWNED" "$EVAL_SANDBOX/ci-gitlab-seed${flag:+-force}.yml"
done

# The owned pipeline keeps its own overwrite guard: a stale file refuses before
# anything is written, and --force replaces only that file.
REFUSE="$EVAL_SANDBOX/ci-gitlab-refuse"
ci_repo "$REFUSE"
mkdir -p "$REFUSE/.gitlab/ci"
printf '# stale pipeline\n' >"$REFUSE/$WF_REL"
(
  cd "$REFUSE" || exit 99
  git add -A
  git commit -qm "seed stale pipeline"
)
cp "$REFUSE/$WF_REL" "$EVAL_SANDBOX/ci-gitlab-stale-copy.yml"
ci_init "$REFUSE" init --ci gitlab
assert_exit "an existing pipeline refuses without a flag" 1
assert_stream_nogrep "the refusal never writes an envelope" "$EVAL_OUT" '"verb": "init"'
assert_file_grep "the refusal names the missing confirm" "$EVAL_ERR" 'without confirm'
assert_file_grep "the re-enter line carries the provider and the confirm" "$EVAL_ERR" \
  '^re-enter: verdict init --preset standard --ci gitlab --agent claude --yes$'
assert_file_eq "the refused pipeline is untouched" "$EVAL_SANDBOX/ci-gitlab-stale-copy.yml" "$REFUSE/$WF_REL"
assert_eq "the pipeline refusal exits 1" "1" "$EVAL_STATUS"
if [ ! -e "$REFUSE/.verdict" ] && [ ! -e "$REFUSE/$ROOT_REL" ]; then
  good "a refused run creates neither .verdict nor the root pipeline"
else
  bad "a refused run wrote before confirming"
fi

ci_init "$REFUSE" init --ci gitlab --force
assert_exit "--force overwrites the stale pipeline" 0
assert_file_grep "the overwrite carries the pinned installer" "$REFUSE/$WF_REL" \
  'raw\.githubusercontent\.com/stainless-code/verdict/[0-9a-f]\{40\}/install\.sh'
if [ -f "$REFUSE/.verdict/config.json" ]; then
  good "--force also writes the control files"
else
  bad "--force wrote no control files"
fi

PRINT="$EVAL_SANDBOX/ci-gitlab-print"
mkdir -p "$PRINT"
ci_init "$PRINT" init --ci gitlab --print
assert_exit "--print succeeds" 0
assert_docs "--print writes no envelope" 0
assert_file_grep "--print heads the pipeline section" "$EVAL_OUT" \
  '^--- \.gitlab/ci/verdict-review\.yml (rendered) ---$'
assert_file_grep "--print heads the root section" "$EVAL_OUT" \
  '^--- \.gitlab-ci\.yml (created only when absent; never overwritten) ---$'
assert_file_grep "--print prints the include to add" "$EVAL_OUT" "^  - local: $WF_REL\$"
if [ ! -e "$PRINT/.verdict" ] && [ ! -e "$PRINT/.gitlab" ] && [ ! -e "$PRINT/$ROOT_REL" ]; then
  good "--print creates no directory and no file"
else
  bad "--print created a path it only renders"
fi

ci_init "$PRINT" init --ci gitlab --print --json
assert_exit "--print --json succeeds" 0
assert_envelope "--print --json envelope"
assert_json_field "--print --json names the provider" "gitlab" '.data.ci'
assert_json_field "--print --json names the pipeline path" "$WF_REL" '.data.workflow_path'
assert_json_field "--print --json names the root path" "$ROOT_REL" '.data.root_path'
assert_json_field "--print --json carries the include snippet" "include:" \
  '.data.include_snippet | split("\n") | .[0]'
assert_json_field "--print --json names the include target" "$WF_REL" \
  '.data.include_snippet | split("\n") | .[1] | ltrimstr("  - local: ")'
assert_json_field "--print --json writes no files" "0" '.data.files | length'
assert_json_field "--print --json omits the write status" "null" '.data.workflow_status'
assert_json_field "--print --json omits the root status" "null" '.data.root_status'
assert_json_field "--print --json keeps the default next line" \
  "write it with: verdict init --ci gitlab" '.next'
if [ ! -e "$PRINT/.verdict" ] && [ ! -e "$PRINT/.gitlab" ] && [ ! -e "$PRINT/$ROOT_REL" ]; then
  good "--print --json creates no directory and no file"
else
  bad "--print --json created a path it only renders"
fi

JSON="$EVAL_SANDBOX/ci-gitlab-json"
ci_repo "$JSON"
ci_init "$JSON" init --ci gitlab --json
assert_exit "the --json create succeeds" 0
assert_envelope "--json create envelope"
assert_json_field "the envelope names the created status" "create" '.data.workflow_status'
assert_json_field "the envelope names the created root status" "create" '.data.root_status'
assert_json_field "the envelope names the root path" "$ROOT_REL" '.data.root_path'
assert_json_field "the envelope carries no printed bytes" "null" '.data.workflow'
assert_json_field "the envelope lists the control files" "3" '.data.files | length'

ci_init "$PRINT" init --ci gitlab --agent amp --json
assert_exit "an agent with no documented key refuses" 1
assert_refusal "the missing-key refusal" "bad-settings"
assert_json_field "the refusal names the escape hatch" "true" \
  '.error.message | contains("--key-secret")'
ci_init "$PRINT" init --ci gitlab --agent amp --key-secret AMP_API_KEY --print
assert_exit "an explicit --key-secret renders any catalog agent" 0
assert_file_grep "the key variable the agent reads is recorded" "$EVAL_OUT" '^    # Set AMP_API_KEY as'
assert_file_grep "an agent with no skills directory installs the shared one" "$EVAL_OUT" \
  '^    VERDICT_SKILL_AGENT: agents$'
assert_file_grep "the skill step reads the mapped variable" "$EVAL_OUT" \
  '^      verdict skill install --agent "\$VERDICT_SKILL_AGENT"$'
assert_eq "the amp render never names another agent's key" "0" \
  "$(grep -c 'ANTHROPIC_API_KEY' "$EVAL_OUT" || true)"
ci_init "$PRINT" init --ci gitlab --agent claude --key-secret REVIEW_KEY --print
assert_exit "an explicit --key-secret on a documented agent prints" 0
assert_file_grep "the key variable aliases the chosen CI/CD variable" "$EVAL_OUT" \
  '^    ANTHROPIC_API_KEY: \$REVIEW_KEY$'
assert_file_nogrep "the alias never names itself" "$EVAL_OUT" 'REVIEW_KEY: $REVIEW_KEY'

# Every path init will not write refuses by name, and writes nothing first.
for shape in gitlab-dir gitlab-ci-dir pipeline-file root-file; do
  LINK="$EVAL_SANDBOX/ci-gitlab-link-$shape"
  OUTSIDE="$EVAL_SANDBOX/ci-gitlab-outside-$shape"
  ci_repo "$LINK"
  case "$shape" in
    gitlab-dir) ln -s "$OUTSIDE" "$LINK/.gitlab" ;;
    gitlab-ci-dir)
      mkdir -p "$LINK/.gitlab"
      ln -s "$OUTSIDE" "$LINK/.gitlab/ci"
      ;;
    pipeline-file)
      mkdir -p "$LINK/.gitlab/ci"
      printf 'x\n' >"$OUTSIDE"
      ln -s "$OUTSIDE" "$LINK/$WF_REL"
      ;;
    root-file)
      printf 'x\n' >"$OUTSIDE"
      ln -s "$OUTSIDE" "$LINK/$ROOT_REL"
      ;;
  esac
  ci_init "$LINK" init --ci gitlab --force
  assert_exit "a symlinked $shape refuses instead of writing through it" 1
  assert_file_grep "the $shape refusal is typed init-failed" "$EVAL_ERR" '^error: init '
  if [ -e "$OUTSIDE" ]; then
    assert_eq "the $shape target is untouched" "x" "$(cat "$OUTSIDE")"
  else
    good "the $shape target was never created"
  fi
  if [ ! -e "$LINK/.verdict" ]; then
    good "the $shape refusal writes nothing"
  else
    bad "the $shape refusal wrote before refusing"
  fi
  rm -rf "$LINK" "$OUTSIDE"
done

FILE_ROOT="$EVAL_SANDBOX/ci-gitlab-root-dir"
ci_repo "$FILE_ROOT"
mkdir -p "$FILE_ROOT/$ROOT_REL"
ci_init "$FILE_ROOT" init --ci gitlab
assert_exit "a directory at the root pipeline path refuses" 1
assert_file_grep "the non-regular root refusal names the path" "$EVAL_ERR" \
  '^error: init will not write \.gitlab-ci\.yml: the path is not a regular file$'
if [ ! -e "$FILE_ROOT/.verdict" ] && [ ! -e "$FILE_ROOT/.gitlab" ]; then
  good "the non-regular root refusal writes nothing"
else
  bad "the non-regular root refusal wrote before refusing"
fi

ci_init "$PRINT" init --ci bogus
assert_exit "an unknown --ci is a usage error" 2
assert_file_grep "the usage error names every provider" "$EVAL_ERR" \
  "unknown --ci 'bogus' for init (want github|forgejo|gitlab)"
ci_init "$PRINT" init --print
assert_exit "--print without --ci is a usage error" 2
assert_file_grep "--print names the flag it needs" "$EVAL_ERR" "--print needs --ci github|forgejo|gitlab"
ci_init "$PRINT" init --agent claude
assert_exit "--agent without --ci is a usage error" 2
assert_file_grep "--agent names the flag it needs" "$EVAL_ERR" "--agent needs --ci github|forgejo|gitlab"
ci_init "$PRINT" init --key-secret REVIEW_KEY
assert_exit "--key-secret without --ci is a usage error" 2
assert_file_grep "--key-secret names the flag it needs" "$EVAL_ERR" \
  "--key-secret needs --ci github|forgejo|gitlab"
ci_init "$PRINT" init --ci
assert_exit "--ci without a value is a usage error" 2
assert_file_grep "--ci names every value" "$EVAL_ERR" "--ci needs a value (want github|forgejo|gitlab)"
ci_init "$PRINT" init --ci=
assert_exit "an empty --ci= is a usage error" 2
assert_file_grep "an empty --ci= names every value" "$EVAL_ERR" \
  "--ci needs a value (want github|forgejo|gitlab)"
ci_init "$PRINT" init --ci ""
assert_exit "an empty --ci operand is a usage error" 2
assert_file_grep "an empty --ci operand names every value" "$EVAL_ERR" \
  "--ci needs a value (want github|forgejo|gitlab)"

MANUAL="$EVAL_ROOT/docs/manual.md"
assert_file_grep "the manual documents the GitLab path" "$MANUAL" '^### GitLab CI$'
assert_file_grep "the manual names the one command" "$MANUAL" 'verdict init --ci gitlab'
assert_file_grep "the manual names the pipeline path" "$MANUAL" '.gitlab/ci/verdict-review.yml'
assert_file_grep "the manual names the root pipeline" "$MANUAL" '.gitlab-ci.yml'
assert_file_grep "the manual names the include" "$MANUAL" "- local: .gitlab/ci/verdict-review.yml" -F
assert_file_grep "the manual names the write token" "$MANUAL" 'GITLAB_TOKEN'
assert_file_grep "the manual names the host binding" "$MANUAL" 'GITLAB_HOST'
assert_file_grep "the manual names the FQDN variable" "$MANUAL" 'CI_SERVER_FQDN'
assert_file_grep "the manual names the provider flag" "$MANUAL" "--provider gitlab" -F
assert_file_grep "the manual states the job token limit" "$MANUAL" 'CI_JOB_TOKEN'
assert_file_grep "the manual names the host CLI" "$MANUAL" 'glab'
assert_file_grep "the manual names the pipeline source" "$MANUAL" 'merge_request_event'
assert_file_grep "the manual names the secret override" "$MANUAL" "--key-secret" -F
assert_file_grep "the recipe names the provider" "$EVAL_ROOT/docs/ci-recipe.md" 'verdict init --ci gitlab'

hoststub_prove_dead gh
hoststub_prove_dead glab
hoststub_prove_dead curl
assert_eq "zero gh stub calls across the init-ci-gitlab legs" "0" "$(hoststub_count gh)"
assert_eq "zero glab stub calls across the init-ci-gitlab legs" "0" "$(hoststub_count glab)"
assert_eq "zero curl stub calls across the init-ci-gitlab legs" "0" "$(hoststub_count curl)"
assert_eq "zero intercepts on the shared stub log" "0" \
  "$(( $(wc -l <"$EVAL_STUBLOG" | tr -d ' ') - stub_before ))"

rm -rf "$EVAL_SANDBOX/ci-gitlab-repo" "$EVAL_SANDBOX/ci-gitlab-refuse" \
  "$EVAL_SANDBOX/ci-gitlab-print" "$EVAL_SANDBOX/ci-gitlab-json" \
  "$EVAL_SANDBOX/ci-gitlab-root-dir" "$BLOCKS" "$SC_LOG" \
  "$EVAL_SANDBOX/ci-gitlab-wf-copy.yml" "$EVAL_SANDBOX/ci-gitlab-root-copy.yml" \
  "$EVAL_SANDBOX/ci-gitlab-stale-copy.yml"

eval_end
