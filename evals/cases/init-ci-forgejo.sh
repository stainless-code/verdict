#!/usr/bin/env bash
#
# `verdict init --ci forgejo`: the generated Forgejo Actions workflow, its
# overwrite guard, the --print shapes, the agent/key wiring, and the documented
# anchors. Every host tool call is stubbed network-dead; init makes none.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=../lib/common.sh
. "$HERE/../lib/common.sh"
# shellcheck source=../lib/hoststub.sh
. "$HERE/../lib/hoststub.sh"

command -v shellcheck >/dev/null 2>&1 || bail "shellcheck is missing: the generated run blocks cannot be graded"

hoststub_init gh curl

WF_REL=".forgejo/workflows/verdict-review.yml"
HEADER='# Generated by `verdict init --ci forgejo`. Review before committing.'
SC_LOG="$EVAL_SANDBOX/ci-forgejo-shellcheck.txt"
: >"$SC_LOG"
stub_before="$(wc -l <"$EVAL_STUBLOG" | tr -d ' ')"

# ci_repo makes one clean repo sandbox with an initial commit.
ci_repo() { # $1 = dir
  mkdir -p "$1"
  (
    cd "$1" || exit 99
    git init -q
    git config user.email "init-ci@example.com"
    git config user.name "init ci"
    echo "probe" >probe.txt
    git add -A
    git commit -qm init
  )
}

# ci_init runs the CLI in dir, capturing EVAL_STATUS/EVAL_OUT/EVAL_ERR.
ci_init() { # $1 = dir, rest = init argv
  local dir="$1"
  shift
  EVAL_STATUS=0
  ( cd "$dir" && PATH="$EVAL_STUBBIN:$PATH" "$EVAL_CLI" "$@" >"$EVAL_OUT" 2>"$EVAL_ERR" ) || EVAL_STATUS=$?
}

REPO="$EVAL_SANDBOX/ci-forgejo-repo"
ci_repo "$REPO"
WF="$REPO/$WF_REL"

ci_init "$REPO" init --ci forgejo
assert_exit "init --ci forgejo writes the workflow" 0
if [ -f "$WF" ]; then
  good "the workflow lands at .forgejo/workflows/verdict-review.yml"
else
  bad "the workflow is missing at $WF_REL"
  bail "nothing to grade"
fi
assert_eq "the first line names the forgejo generator" "$HEADER" "$(head -1 "$WF")"
assert_file_grep "the checkout pin is a full commit" "$WF" '^        uses: actions/checkout@[0-9a-f]\{40\} # v7$'
assert_file_grep "the verdict action is fully qualified and pinned" "$WF" \
  '^        uses: https://github\.com/stainless-code/verdict/setup-verdict@[0-9a-f]\{40\} # v0\.7\.0$'
assert_file_nogrep "the verdict action never uses the short form" "$WF" \
  '^        uses: stainless-code/verdict/setup-verdict@'
assert_file_grep "the workflow triggers on pull_request" "$WF" '^  pull_request:$'
assert_file_grep "the three review events are the trigger" "$WF" '^    types: \[opened, synchronize, reopened\]$'
assert_file_grep "the job budget is pinned" "$WF" '^    timeout-minutes: 30$'
assert_file_grep "the job refuses fork pull requests" "$WF" \
  '^    if: github.event.pull_request.head.repo.full_name == github.repository$'
assert_file_nogrep "never runs on pull_request_target" "$WF" 'pull_request_target'
assert_file_nogrep "never traces the shell" "$WF" 'set -x'

assert_file_nogrep "the forgejo render carries no permissions block" "$WF" 'permissions:'
assert_file_nogrep "the forgejo render omits the readiness step" "$WF" 'Readiness pre-check'
assert_file_nogrep "the forgejo render never names the GitHub secret alias" "$WF" 'secrets.GITHUB_TOKEN'

assert_file_grep "the host comes from the runner context" "$WF" \
  '          FORGEJO_HOST: ${{ github.server_url }}' -F
assert_file_grep "the token is the automatic context token" "$WF" \
  '          FORGEJO_TOKEN: ${{ github.token }}' -F
assert_file_grep "only the fetch step names the provider" "$WF" \
  '          verdict fetch "$VERDICT_REPOSITORY" "$VERDICT_PR" --provider forgejo$'
assert_eq "the provider flag appears exactly once" "1" "$(grep -c -- '--provider forgejo' "$WF")"

assert_file_grep "the agent step clears GH_TOKEN" "$WF" '^          GH_TOKEN: ""$'
assert_file_grep "the agent step clears GITHUB_TOKEN" "$WF" '^          GITHUB_TOKEN: ""$'
assert_file_grep "the agent step clears FORGEJO_TOKEN" "$WF" '^          FORGEJO_TOKEN: ""$'
assert_file_grep "the agent name is baked from the catalog" "$WF" '^          VERDICT_AGENT: claude$'
assert_file_grep "the model comes from a repository variable" "$WF" '          VERDICT_MODEL: ${{ vars.VERDICT_MODEL }}' -F
assert_file_grep "the model key arrives as one repository secret" "$WF" \
  '          ANTHROPIC_API_KEY: ${{ secrets.ANTHROPIC_API_KEY }}' -F
assert_file_grep "the agent's permission hint is a comment" "$WF" \
  '^          # verdict never bakes a permission flag: .*--permission-mode acceptEdits,$'
assert_file_grep "the gate is the composed verb" "$WF" \
  '^            --max-severity critical --require-head --live auto$'
assert_file_grep "the runner prerequisite is stated" "$WF" \
  '^          # Install claude on the runner before this step: verdict installs$'
assert_file_grep "the catalog install command rides along as a comment" "$WF" \
  '          #   curl -fsSL https://claude.ai/install.sh | bash' -F
not_a_comment="$(grep -n 'install\.sh' "$WF" \
  | grep -v -E '^[0-9]+:          #   ' || true)"
assert_eq "no installer runs as a step" "" "$not_a_comment"
leaked="$(grep -n 'secrets\.' "$WF" \
  | grep -v -E '^[0-9]+:          [A-Z_][A-Z0-9_]*: \$\{\{ secrets\.[A-Z_][A-Z0-9_]* \}\}$' || true)"
assert_eq "every secret stays an env assignment" "" "$leaked"

assert_eq "the workflow carries eight inline steps" "8" "$(grep -c '^      - name: ' "$WF")"
assert_eq "the steps run in the reviewed order" \
  "Checkout|Install verdict|Install the review skill|Fetch the PR bundle|Agent review (verdict run --agent, your agent + your key)|Post the review|Review summary (advisory, never gates)|Merge gate (findings + freshness + coverage + live threads)" \
  "$(grep '^      - name: ' "$WF" | sed 's/^      - name: //' | paste -sd'|' -)"
assert_eq "the pipeline posts before it gates" "skill install|fetch|run|post|report|gate" \
  "$(grep -oE '^          verdict [a-z]+( install)?' "$WF" | sed 's/^          verdict //' | paste -sd'|' -)"

BLOCKS="$EVAL_SANDBOX/ci-forgejo-runs"
mkdir -p "$BLOCKS"
awk -v dir="$BLOCKS" '
  /^        run: \|$/ { open=1; n++; f=sprintf("%s/run-%02d.sh", dir, n); print "#!/usr/bin/env bash" > f; next }
  open && /^          / { sub(/^          /, ""); print > f; next }
  { open=0 }
' "$WF"
problems=""
blocks=0
for block in "$BLOCKS"/run-*.sh; do
  blocks=$((blocks + 1))
  bash -n "$block" 2>>"$SC_LOG" || problems="$problems parse:$(basename "$block")"
  shellcheck -S warning "$block" >>"$SC_LOG" 2>&1 || problems="$problems shellcheck:$(basename "$block")"
  if grep -q 'secrets\.' "$block"; then problems="$problems secret:$(basename "$block")"; fi
  if grep -qF '${{' "$block"; then problems="$problems expression:$(basename "$block")"; fi
done
assert_eq "six run blocks were extracted" "6" "$blocks"
assert_eq "every run block parses, checks, and interpolates nothing" "" "$problems"
if [ -s "$SC_LOG" ]; then
  bad "shellcheck reported on the generated run blocks: $(head -20 "$SC_LOG" | tr '\n' ' ')"
else
  good "shellcheck -S warning is silent on every generated run block"
fi

cp "$WF" "$EVAL_SANDBOX/ci-forgejo-wf-copy.yml"
ci_init "$REPO" init --ci forgejo
assert_exit "a second run is idempotent" 0
if grep -q "keep: $WF_REL (already up to date)" "$EVAL_OUT"; then
  good "the identical workflow reads as keep"
else
  bad "the idempotent re-run did not report keep"
fi
assert_file_eq "the kept workflow is byte-identical" "$EVAL_SANDBOX/ci-forgejo-wf-copy.yml" "$WF"

REFUSE="$EVAL_SANDBOX/ci-forgejo-refuse"
ci_repo "$REFUSE"
mkdir -p "$REFUSE/.forgejo/workflows"
printf '# stale workflow\n' >"$REFUSE/$WF_REL"
(
  cd "$REFUSE" || exit 99
  git add -A
  git commit -qm "seed stale workflow"
)
cp "$REFUSE/$WF_REL" "$EVAL_SANDBOX/ci-forgejo-stale-copy.yml"
ci_init "$REFUSE" init --ci forgejo
assert_exit "an existing workflow refuses without a flag" 1
assert_stream_nogrep "the refusal never writes an envelope" "$EVAL_OUT" '"verb": "init"'
assert_file_grep "the refusal names the missing confirm" "$EVAL_ERR" 'without confirm'
assert_file_grep "the re-enter line carries the provider and the confirm" "$EVAL_ERR" \
  '^re-enter: verdict init --preset standard --ci forgejo --agent claude --yes$'
assert_file_eq "the refused workflow is untouched" "$EVAL_SANDBOX/ci-forgejo-stale-copy.yml" "$REFUSE/$WF_REL"
if [ ! -e "$REFUSE/.verdict" ]; then
  good "a refused run creates no .verdict directory"
else
  bad "a refused run created .verdict before confirming"
fi
assert_eq "the refusal is the documented exit code" "1" "$EVAL_STATUS"

ci_init "$REFUSE" init --ci forgejo --force
assert_exit "--force overwrites the workflow" 0
assert_file_grep "the overwrite carries the fully-qualified verdict action" "$REFUSE/$WF_REL" \
  '^        uses: https://github\.com/stainless-code/verdict/setup-verdict@[0-9a-f]\{40\} # v0\.7\.0$'
if [ -f "$REFUSE/.verdict/config.json" ]; then
  good "--force also writes the control files"
else
  bad "--force wrote no control files"
fi

PRINT="$EVAL_SANDBOX/ci-forgejo-print"
mkdir -p "$PRINT"
ci_init "$PRINT" init --ci forgejo --print
assert_exit "--print succeeds" 0
assert_docs "--print writes no envelope" 0
assert_eq "--print starts with the forgejo header" "$HEADER" "$(head -1 "$EVAL_OUT")"
assert_file_grep "--print carries the merge gate" "$EVAL_OUT" \
  '^            --max-severity critical --require-head --live auto$'
if [ ! -e "$PRINT/.verdict" ] && [ ! -e "$PRINT/.forgejo" ]; then
  good "--print creates no directory"
else
  bad "--print created a directory it only renders"
fi

ci_init "$PRINT" init --ci forgejo --print --json
assert_exit "--print --json succeeds" 0
assert_envelope "--print --json envelope"
assert_json_field "--print --json names the provider" "forgejo" '.data.ci'
assert_json_field "--print --json names the workflow path" "$WF_REL" '.data.workflow_path'
assert_json_field "--print --json writes no files" "0" '.data.files | length'
assert_json_field "--print --json omits the write status" "null" '.data.workflow_status'
assert_json_field "--print --json carries the bytes" "$HEADER" '.data.workflow | split("\n") | .[0]'
assert_json_field "--print --json keeps the default next line" \
  "write it with: verdict init --ci forgejo" '.next'
if [ ! -e "$PRINT/.verdict" ] && [ ! -e "$PRINT/.forgejo" ]; then
  good "--print --json creates no directory"
else
  bad "--print --json created a directory it only renders"
fi

JSON="$EVAL_SANDBOX/ci-forgejo-json"
ci_repo "$JSON"
ci_init "$JSON" init --ci forgejo --json
assert_exit "the --json create succeeds" 0
assert_envelope "--json create envelope"
assert_json_field "the envelope names the created status" "create" '.data.workflow_status'
assert_json_field "the envelope names the forgejo path" "$WF_REL" '.data.workflow_path'
assert_json_field "the envelope carries no printed bytes" "null" '.data.workflow'
assert_json_field "the envelope lists the control files" "3" '.data.files | length'

ci_init "$PRINT" init --ci forgejo --agent amp --json
assert_exit "an agent with no documented key refuses" 1
assert_refusal "the missing-key refusal" "bad-settings"
assert_json_field "the refusal names the escape hatch" "true" \
  '.error.message | contains("--key-secret")'
ci_init "$PRINT" init --ci forgejo --agent amp --key-secret AMP_API_KEY --print
assert_exit "an explicit --key-secret renders any catalog agent" 0
assert_file_grep "the override reaches the agent step" "$EVAL_OUT" \
  '          AMP_API_KEY: ${{ secrets.AMP_API_KEY }}' -F
assert_file_grep "an agent with no skills directory installs the shared one" "$EVAL_OUT" \
  '^          VERDICT_SKILL_AGENT: agents$'
assert_file_grep "a hintless agent says so" "$EVAL_OUT" '^          # This agent has no documented permission flag\.$'
ci_init "$PRINT" init --ci forgejo --agent no-such-agent --json
assert_exit "an unknown --agent refuses" 1
assert_refusal "the unknown-agent refusal" "unknown-agent"
ci_init "$PRINT" init --ci forgejo --key-secret bad-name --print --json
assert_exit "a malformed --key-secret refuses" 1
assert_refusal "the malformed-secret refusal" "bad-settings"

ci_init "$PRINT" init --ci bogus
assert_exit "an unknown --ci is a usage error" 2
assert_file_grep "the usage error names both providers" "$EVAL_ERR" \
  "unknown --ci 'bogus' for init (want github|forgejo)"
ci_init "$PRINT" init --print
assert_exit "--print without --ci is a usage error" 2
assert_file_grep "--print names the flag it needs" "$EVAL_ERR" "--print needs --ci github|forgejo"
ci_init "$PRINT" init --agent claude
assert_exit "--agent without --ci is a usage error" 2
assert_file_grep "--agent names the flag it needs" "$EVAL_ERR" "--agent needs --ci github|forgejo"
ci_init "$PRINT" init --ci
assert_exit "--ci without a value is a usage error" 2
assert_file_grep "--ci names both values" "$EVAL_ERR" "--ci needs a value (want github|forgejo)"
ci_init "$PRINT" init --ci=
assert_exit "an empty --ci= is a usage error" 2
assert_file_grep "an empty --ci= names both values" "$EVAL_ERR" "--ci needs a value (want github|forgejo)"
ci_init "$PRINT" init --ci ""
assert_exit "an empty --ci operand is a usage error" 2
assert_file_grep "an empty --ci operand names both values" "$EVAL_ERR" \
  "--ci needs a value (want github|forgejo)"

LINK="$EVAL_SANDBOX/ci-forgejo-link"
ci_repo "$LINK"
ln -s outside "$LINK/.forgejo"
ci_init "$LINK" init --ci forgejo --force
assert_exit "a symlinked .forgejo refuses instead of writing through it" 1
assert_file_grep "the symlink refusal is typed init-failed" "$EVAL_ERR" \
  'error: init could not write \.forgejo/workflows/verdict-review\.yml'
if [ ! -e "$LINK/outside/workflows" ]; then
  good "the symlink target is untouched"
else
  bad "init wrote through the symlink"
fi
if [ ! -e "$LINK/.verdict" ]; then
  good "the symlinked .forgejo refusal creates no .verdict directory"
else
  bad "the symlinked .forgejo refusal wrote .verdict before refusing"
fi

KEEPLINK="$EVAL_SANDBOX/ci-forgejo-link-keep"
OUTSIDE="$EVAL_SANDBOX/ci-forgejo-link-outside"
ci_repo "$KEEPLINK"
mkdir -p "$OUTSIDE/workflows"
cp "$WF" "$OUTSIDE/workflows/verdict-review.yml"
ln -s "$OUTSIDE" "$KEEPLINK/.forgejo"
ci_init "$KEEPLINK" init --ci forgejo
assert_exit "a symlinked .forgejo holding the identical workflow still refuses" 1
assert_stream_nogrep "the symlinked workflow never reads as keep" "$EVAL_ERR" 'keep:'
assert_file_grep "the identical-workflow refusal is typed init-failed" "$EVAL_ERR" \
  'error: init could not write \.forgejo/workflows/verdict-review\.yml'
assert_file_eq "the identical workflow behind the link is untouched" "$WF" \
  "$OUTSIDE/workflows/verdict-review.yml"
if [ ! -e "$KEEPLINK/.verdict" ]; then
  good "the identical-workflow refusal creates no .verdict directory"
else
  bad "the identical-workflow refusal wrote .verdict before refusing"
fi

FILEFORGEJO="$EVAL_SANDBOX/ci-forgejo-file"
ci_repo "$FILEFORGEJO"
printf 'not a directory\n' >"$FILEFORGEJO/.forgejo"
ci_init "$FILEFORGEJO" init --ci forgejo
assert_exit "a plain file at .forgejo refuses" 1
assert_file_grep "the plain-file refusal is typed init-failed" "$EVAL_ERR" \
  'error: init could not write \.forgejo/workflows/verdict-review\.yml'
if [ ! -e "$FILEFORGEJO/.verdict" ]; then
  good "the plain-file refusal creates no .verdict directory"
else
  bad "the plain-file refusal wrote .verdict before refusing"
fi

MANUAL="$EVAL_ROOT/docs/manual.md"
assert_file_grep "the manual documents the forgejo path" "$MANUAL" '^### Forgejo Actions$'
assert_file_grep "the manual names the one command" "$MANUAL" 'verdict init --ci forgejo'
assert_file_grep "the manual names the workflow path" "$MANUAL" '.forgejo/workflows/verdict-review.yml'
assert_file_grep "the manual names the host context" "$MANUAL" 'FORGEJO_HOST'
assert_file_grep "the manual names the token context" "$MANUAL" 'FORGEJO_TOKEN'
assert_file_grep "the manual carries the runner label" "$MANUAL" 'ubuntu-latest'
assert_file_grep "the manual names cosign" "$MANUAL" 'cosign'
assert_file_grep "the manual states the fork-PR consequence" "$MANUAL" 'reads as a pass to branch'
assert_file_grep "the recipe names the provider" "$EVAL_ROOT/docs/ci-recipe.md" 'verdict init --ci forgejo'

assert_eq "zero gh stub calls across the init-ci-forgejo legs" "0" "$(hoststub_count gh)"
assert_eq "zero curl stub calls across the init-ci-forgejo legs" "0" "$(hoststub_count curl)"
assert_eq "zero gh intercepts on the shared stub log" "0" \
  "$(( $(wc -l <"$EVAL_STUBLOG" | tr -d ' ') - stub_before ))"

rm -rf "$EVAL_SANDBOX/ci-forgejo-repo" "$EVAL_SANDBOX/ci-forgejo-refuse" \
  "$EVAL_SANDBOX/ci-forgejo-print" "$EVAL_SANDBOX/ci-forgejo-json" \
  "$EVAL_SANDBOX/ci-forgejo-link" "$EVAL_SANDBOX/ci-forgejo-link-keep" \
  "$EVAL_SANDBOX/ci-forgejo-link-outside" "$EVAL_SANDBOX/ci-forgejo-file" \
  "$BLOCKS" "$SC_LOG" "$EVAL_SANDBOX/ci-forgejo-wf-copy.yml" \
  "$EVAL_SANDBOX/ci-forgejo-stale-copy.yml"

eval_end
